    /**
     * Build a FOREIGN KEY constraint definition for CREATE TABLE
     *
     * DB2 limitation: ON UPDATE CASCADE is not supported.
     * DB2 only supports RESTRICT or NO ACTION for ON UPDATE.
     * This method converts CASCADE to NO ACTION for ON UPDATE.
     *
     * @param   array   $fk          Foreign key definition
     * @param   string  $tableName   Table name
     * @return  string  The constraint definition SQL
     */
    public function buildForeignKeyDefinition(array $fk, string $tableName): string
    {
        $refTable = $this->replacePrefix($fk['referencedTable']);
        $fkName = !empty($fk['name']) ? $fk['name'] : "fk_{$tableName}_{$fk['column']}";
        $constraintName = $this->quoteName($fkName);
        $fkColumn = $this->quoteName($fk['column']);
        $refTableQuoted = $this->quoteName($refTable);
        $refColumn = $this->quoteName($fk['referencedColumn']);

        $constraint = "CONSTRAINT $constraintName ";
        $constraint .= "FOREIGN KEY ($fkColumn) ";
        $constraint .= "REFERENCES $refTableQuoted ($refColumn) ";
        $constraint .= "ON DELETE {$fk['onDelete']} ";

        // DB2 doesn't support CASCADE for ON UPDATE - convert to NO ACTION
        $onUpdate = strtoupper($fk['onUpdate']) === 'CASCADE' ? 'NO ACTION' : $fk['onUpdate'];
        $constraint .= "ON UPDATE $onUpdate";

        return $constraint;
    }

    /**
     * Build an auto-increment column definition
     *
     * DB2 uses GENERATED ALWAYS AS IDENTITY syntax for auto-increment.
     * Unlike AUTO_INCREMENT in MySQL, DB2's IDENTITY columns are created
     * inline with the column definition.
     *
     * @param   string  $quotedName  The quoted column name
     * @param   string  $type        The column type (e.g., 'INTEGER')
     * @return  string  The column definition SQL
     */
    public function buildAutoIncrementColumn(string $quotedName, string $type): string
    {
        // Normalize the type to remove MySQL-specific syntax
        $type = $this->normalizeColumnType($type, []);
        // Use GENERATED BY DEFAULT to allow explicit ID values (e.g., for testing or data migration)
        return "$quotedName $type GENERATED BY DEFAULT AS IDENTITY (START WITH 1, INCREMENT BY 1) PRIMARY KEY";
    }

    /**
     * Normalize column type from generic/MySQL syntax to DB2 syntax
     *
     * Handles two cases:
     * 1. Abstract types (string, integer, etc.) → use Grammar type mapping
     * 2. MySQL-specific syntax → convert to DB2 equivalents
     *
     * Conversions:
     * - INT(11) → INTEGER
     * - INT(11) UNSIGNED → INTEGER
     * - BIGINT(20) → BIGINT
     * - VARCHAR(255) → VARCHAR(255) (preserved)
     * - Removes UNSIGNED keyword (not supported by DB2)
     *
     * @param   string  $type       The column type definition
     * @param   array   $modifiers  Column modifiers (length, precision, scale, etc.)
     * @return  string  The normalized DB2 type
     */
    public function normalizeColumnType(string $type, array $modifiers = []): string
    {
        // Normalize type to lowercase for typeMap lookup (AlterTableBuilder uses uppercase)
        $normalizedType = strtolower($type);

        // Check if it's an abstract type that the Grammar can map
        // (e.g., 'string' → 'VARCHAR', 'integer' → 'INTEGER', 'TEXT' → 'CLOB')
        if ($this->getSchemaGrammar()->getTypeMapping($normalizedType) !== null) {
            // Pass the normalized lowercase type to parent
            return parent::normalizeColumnType($normalizedType, $modifiers);
        }

        // Not an abstract type - handle MySQL-specific syntax

        // Convert MySQL SET type to VARCHAR (DB2 doesn't have SET type)
        // SET('value1', 'value2', ...) → VARCHAR(255)
        if (preg_match('/^SET\(/i', $type)) {
            return 'VARCHAR(255)';
        }

        // Remove UNSIGNED keyword - DB2 doesn't support it
        $type = preg_replace('/\s+UNSIGNED/i', '', $type);

        // Map MySQL integer types to DB2 types, removing length specifications
        // INT(11) → INTEGER, BIGINT(20) → BIGINT, etc.
        $type = preg_replace('/^INT\(\d+\)/i', 'INTEGER', $type);
        $type = preg_replace('/^BIGINT\(\d+\)/i', 'BIGINT', $type);
        $type = preg_replace('/^SMALLINT\(\d+\)/i', 'SMALLINT', $type);
        $type = preg_replace('/^TINYINT\(\d+\)/i', 'SMALLINT', $type);  // DB2 doesn't have TINYINT

        // For bare INT without length, convert to INTEGER
        $type = preg_replace('/^INT$/i', 'INTEGER', $type);

        return trim($type);
    }

