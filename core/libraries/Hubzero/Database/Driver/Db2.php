    /**
     * Truncate a table
     *
     * @param   string  $table   The table to truncate
     * @param   int     $nextId  The next auto-increment value (ignored on DB2)
     * @return  $this
     */
    public function truncateTable($table, int $nextId = 1)
    {
        $table = strtoupper($this->replacePrefix($table));

        // DB2 requires TRUNCATE to be the first statement in a unit of work (SQL0428N).
        // Issue a raw COMMIT via exec() to end any pending implicit transaction.
        // PDO::commit() only works with explicit beginTransaction(); raw SQL works always.
        if ($this->transactionDepth === 0) {
            try {
                $this->connection->exec('COMMIT');
            } catch (\Exception $e) {
                // Nothing to commit — ignore
            }
        }

        $this->setQuery('TRUNCATE TABLE ' . $this->quoteName($table) . ' IMMEDIATE');
        $this->execute();

        // DB2's TRUNCATE does not reset identity columns.
        // Find and reset any identity column to the specified nextId.
        $identityCol = $this->findIdentityColumn($table);
        if ($identityCol) {
            $this->setQuery(
                'ALTER TABLE ' . $this->quoteName($table)
                . ' ALTER COLUMN ' . $this->quoteName($identityCol)
                . ' RESTART WITH ' . $nextId
            );
            $this->execute();
        }

        return $this;
    }

