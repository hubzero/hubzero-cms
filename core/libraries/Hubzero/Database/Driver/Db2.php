    /**
     * Normalize DB2 timestamp values by stripping microseconds
     *
     * DB2 TIMESTAMP columns include microseconds by default (e.g., '2024-06-15 10:30:00.000000')
     * but most applications expect standard format without microseconds.
     *
     * @param   mixed  $value  The value to normalize
     * @return  mixed  Normalized value
     */
    protected function normalizeTimestamp($value)
    {
        if (is_string($value) && preg_match('/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}\.\d+$/', $value)) {
            // Strip microseconds: '2024-06-15 10:30:00.000000' → '2024-06-15 10:30:00'
            return preg_replace('/\.\d+$/', '', $value);
        }
        return $value;
    }

    /**
     * Normalize timestamps in an object
     *
     * @param   object  $object  The object to normalize
     * @return  object  The normalized object
     */
    protected function normalizeObjectTimestamps($object)
    {
        if (!is_object($object)) {
            return $object;
        }

        foreach (get_object_vars($object) as $key => $value) {
            $object->$key = $this->normalizeTimestamp($value);
        }

        return $object;
    }

    /**
     * {@inheritdoc}
     */
    public function loadObject($class = 'stdClass')
    {
        $object = parent::loadObject($class);
        return $object ? $this->normalizeObjectTimestamps($object) : $object;
    }

    /**
     * {@inheritdoc}
     */
    public function loadObjectList($key = '', $class = 'stdClass')
    {
        $list = parent::loadObjectList($key, $class);

        if (is_array($list)) {
            foreach ($list as $k => $object) {
                $list[$k] = $this->normalizeObjectTimestamps($object);
            }
        }

        return $list;
    }
