    /**
     * Gets the auto-increment value for the given table
     *
     * DB2 uses identity columns or sequences.
     * This attempts to find a sequence named {table}_SEQ or identity column.
     *
     * @param   string    $table  The table for which to retrieve the value
     * @return  int|bool
     */
    public function getAutoIncrement($table)
    {
        $table = strtoupper($this->replacePrefix($table));

        // Find the identity column
        $this->setQuery("
            SELECT CAST(colname AS VARCHAR(128))
            FROM syscat.columns
            WHERE tabname = " . $this->quote($table) . "
            AND identity = 'Y'
            FETCH FIRST 1 ROW ONLY
        ");
        $identityCol = $this->loadResult();

        if ($identityCol) {
            // Query the maximum value from the table
            // This is the most reliable way to get the next auto-increment value
            $this->setQuery(
                "SELECT MAX(" . $this->quoteName($identityCol) . ") " .
                "FROM " . $this->quoteName($table)
            );

            try {
                $maxValue = $this->loadResult();
                if ($maxValue !== null) {
                    return (int) $maxValue + 1;
                }
            } catch (\Exception $e) {
                // Table might be empty or inaccessible
            }

            // If table is empty, return 1 (default start value)
            return 1;
        }

        // Fallback: try to find a manually created sequence for this table
        $seqNames = [
            $table . '_SEQ',
            $table . '_ID_SEQ',
        ];

        foreach ($seqNames as $seqName) {
            $this->setQuery(
                "SELECT NEXTCACHEFIRSTVALUE FROM syscat.sequences"
                . " WHERE seqname = " . $this->quote($seqName)
            );
            try {
                $result = $this->loadResult();
                if ($result !== null) {
                    return (int) $result;
                }
            } catch (\Exception $e) {
                // Continue to next
            }
        }

        return false;
    }

    /**
     * Sets the auto-increment starting value for the given table
     *
     * DB2 uses sequences; this modifies the sequence if found
     *
     * @param   string  $table  The table name
     * @param   int     $value  The auto-increment starting value
     * @return  bool
     */
    public function setAutoIncrement($table, $value): bool
    {
        $table = strtoupper($this->replacePrefix($table));
        $value = (int) $value;

        // DB2 normalizes 0 to 1 - if caller wants next insert to get ID=1, pass 0 or 1
        if ($value == 0) {
            $value = 1;
        }

        // Find the identity column and reset it using ALTER TABLE
        $identityCol = $this->findIdentityColumn($table);
        if ($identityCol) {
            $this->setQuery(
                'ALTER TABLE ' . $this->quoteName($table)
                . ' ALTER COLUMN ' . $this->quoteName($identityCol)
                . ' RESTART WITH ' . $value
            );
            try {
                $this->execute();
                return true;
            } catch (\Exception $e) {
                // Failed to reset identity column
                return false;
            }
        }

        // No identity column found - try sequences as fallback
        $seqNames = [
            $table . '_SEQ',
            $table . '_ID_SEQ',
        ];

        foreach ($seqNames as $seqName) {
            if ($this->sequenceExists($seqName)) {
                $this->setQuery("ALTER SEQUENCE " . $this->quoteName($seqName) . " RESTART WITH {$value}");
                try {
                    $this->execute();
                    return true;
                } catch (\Exception $e) {
                    // Continue
                }
            }
        }

        return false;
    }

