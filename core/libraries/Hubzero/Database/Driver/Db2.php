     * DB2's DROP TABLE IF EXISTS can still throw SQL0204N in some edge
     * cases, so this method catches and ignores "undefined name" errors
     * when $ifExists is true.
     *
     * @param   string   $tableName  The name of the database table to drop
     * @param   boolean  $ifExists   Optionally specify that the table must exist before it is dropped
     * @return  $this
