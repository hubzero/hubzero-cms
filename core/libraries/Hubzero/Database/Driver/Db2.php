    /**
     * Gets foreign key constraints for a table
     *
     * @param   string  $table  The table name
     * @return  array
     */
    public function getForeignKeys($table)
    {
        $table = strtoupper($this->replacePrefix($table));

        $sql = "SELECT
                    r.constname AS constraint_name,
                    kc.colname AS column_name,
                    r.reftabname AS foreign_table,
                    rkc.colname AS foreign_column,
                    r.deleterule AS delete_rule,
                    r.updaterule AS update_rule
                FROM syscat.references r
                JOIN syscat.keycoluse kc ON r.constname = kc.constname AND r.tabschema = kc.tabschema
                JOIN syscat.keycoluse rkc ON r.refkeyname = rkc.constname
                    AND r.reftabschema = rkc.tabschema AND kc.colseq = rkc.colseq
                WHERE r.tabname = " . $this->quote($table) . "
                AND r.tabschema = CURRENT SCHEMA
                ORDER BY r.constname, kc.colseq";

        $this->setQuery($sql);
        $rows = $this->loadObjectList();

        // Group by constraint name
        $foreignKeys = [];
        foreach ($rows as $row) {
            $name = $row->constraint_name;

            if (!isset($foreignKeys[$name])) {
                $foreignKeys[$name] = (object) [
                    'name'            => $name,
                    'columns'         => [],
                    'foreign_table'   => $row->foreign_table,
                    'foreign_columns' => [],
                    'on_update'       => $this->translateRule($row->update_rule),
                    'on_delete'       => $this->translateRule($row->delete_rule),
                ];
            }

            $foreignKeys[$name]->columns[] = $row->column_name;
            $foreignKeys[$name]->foreign_columns[] = $row->foreign_column;
        }

        return array_values($foreignKeys);
    }

    /**
     * Adds a foreign key constraint to a table
     *
     * @param   string        $table          The table to add the FK to
     * @param   string        $constraint     The constraint name
     * @param   string|array  $columns        The local column(s)
     * @param   string        $foreignTable   The referenced table
     * @param   string|array  $foreignColumns The referenced column(s)
     * @param   string        $onUpdate       ON UPDATE action (default NO ACTION)
     * @param   string        $onDelete       ON DELETE action (default NO ACTION)
     * @return  bool
     */
    public function addForeignKey(
        $table,
        $constraint,
        $columns,
        $foreignTable,
        $foreignColumns,
        $onUpdate = 'NO ACTION',
        $onDelete = 'NO ACTION'
    ) {
        $table        = strtoupper($this->replacePrefix($table));
        $foreignTable = strtoupper($this->replacePrefix($foreignTable));

        $columnList        = implode(', ', array_map([$this, 'quoteName'], (array) $columns));
        $foreignColumnList = implode(', ', array_map([$this, 'quoteName'], (array) $foreignColumns));

        $sql = 'ALTER TABLE ' . $this->quoteName($table)
            . ' ADD CONSTRAINT ' . $this->quoteName(strtoupper($constraint))
            . ' FOREIGN KEY (' . $columnList . ')'
            . ' REFERENCES ' . $this->quoteName($foreignTable) . ' (' . $foreignColumnList . ')'
            . ' ON UPDATE ' . strtoupper($onUpdate)
            . ' ON DELETE ' . strtoupper($onDelete);

        $this->setQuery($sql);

        try {
            $this->execute();
            return true;
        } catch (\Exception $e) {
            return false;
        }
    }

