    /**
     * Translate DB2 rule code to standard action
     *
     * @param   string  $rule  The DB2 rule code
     * @return  string
     */
    protected function translateRule($rule)
    {
        switch ($rule) {
            case 'A':
                return 'NO ACTION';
            case 'C':
                return 'CASCADE';
            case 'N':
                return 'SET NULL';
            case 'R':
                return 'RESTRICT';
            default:
                return 'NO ACTION';
        }
    }

