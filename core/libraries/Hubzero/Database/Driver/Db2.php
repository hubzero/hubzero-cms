    /**
     * Returns the SQL for date formatting
     *
     * DB2 uses VARCHAR_FORMAT(date, format)
     *
     * @param   string  $date    The date column or value
     * @param   string  $format  The format string (MySQL format codes)
     * @return  string
     */
    public function sqlDateFormat(string $date, string $format): string
    {
        // Convert MySQL format codes to DB2 VARCHAR_FORMAT format
        $conversions = [
            '%Y' => 'YYYY',
            '%y' => 'YY',
            '%m' => 'MM',
            '%c' => 'M',
            '%d' => 'DD',
            '%e' => 'D',
            '%H' => 'HH24',
            '%h' => 'HH12',
            '%i' => 'MI',
            '%s' => 'SS',
            '%p' => 'AM',
            '%M' => 'Month',
            '%b' => 'Mon',
            '%W' => 'Day',
            '%a' => 'Dy',
            '%j' => 'DDD',
        ];

        $db2Format = str_replace(array_keys($conversions), array_values($conversions), $format);

        return 'VARCHAR_FORMAT(' . $date . ', ' . $this->quote($db2Format) . ')';
    }

