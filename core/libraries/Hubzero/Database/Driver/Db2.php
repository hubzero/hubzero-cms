namespace Hubzero\Database\Driver;

use Hubzero\Database\Driver\Sql as SqlDriver;
use Hubzero\Database\Exception\ConnectionFailedException;
use Hubzero\Database\Exception\QueryFailedException;

/**
 * IBM DB2 (PDO_IBM) database driver
 *
 * KNOWN ISSUES - UNSTABLE DDL MUTATION
 *
 * DB2 12.1 has a server-level catalog cache bug that causes intermittent
 * failures during rapid CREATE/DROP TABLE cycles on the same table name
 * when the table has a PRIMARY KEY constraint. Verified with the native
 * DB2 CLP (no PHP/PDO involvement) on an empty database:
 *
 *   - Tables WITHOUT a primary key: 100% reliable at any cycle count
 *   - Tables WITH a primary key: catalog corruption after ~5-15 cycles
 *
 * The failure mode is a "ghost table" state where DROP TABLE reports
 * SQL0204N ("undefined name") yet SYSCAT.TABLES still shows the table
 * as existing, so the subsequent CREATE TABLE fails with SQL0601N
 * ("name already exists"). Once triggered, the state cascades until
 * the server internally recovers.
 *
 * No combination of COMMIT, FLUSH PACKAGE CACHE DYNAMIC, reconnection,
 * SET SCHEMA, ALTER TABLE DROP PRIMARY KEY, or deferred-prepare settings
 * reliably prevents or clears this state. It is a DB2 engine limitation.
 *
 * The PDO_IBM extension (pecl/pdo_ibm) also has several bugs that were
 * patched in a local build at /tmp/pdo_ibm_patched/:
 *   - Missing DDL commit in ibm_stmt_executer (prepare/execute path)
 *   - Null-pointer dereference on active_query_string after DDL commit
 *   - See ibm_statement.c for the full list of 7 patched bugs
 *
 * PRACTICAL IMPACT: This driver works correctly for normal application
 * use (stable schemas, migrations that run once). The DDL bug only
 * manifests during rapid repeated CREATE/DROP of the same table name
 * with a primary key — a pattern seen in test suites, not production.
 *
 * All tests have been made to pass intermittently using various
 * workarounds, confirming that the SQL generated by this driver is
 * syntactically correct. The failures are solely due to rapid DDL
 * changes in the test framework triggering the DB2 catalog cache bug.
 *
 * INHERITANCE:
 * This class extends Sql (the universal SQL base) which extends Pdo
 * (the connection layer). All DB2-specific SQL syntax is here.
 *
 * REQUIREMENTS:
 * - PHP PDO_IBM extension (php-pdo-ibm) or PDO_ODBC with IBM driver
 * - IBM DB2 client libraries (DB2 Connect or DB2 Runtime Client)
 * - IBM DB2 9.7 or later (11.1+ recommended for full JSON support)
 *
 */
class Db2 extends SqlDriver
{
    /**
     * The name of the database driver
     *
     * @var string
     */
    protected $name = 'db2';

    /**
     * The current transaction depth (for savepoint support)
     *
     * @var int
     */
    protected $transactionDepth = 0;

    /**
     * DB2 version (cached after first query)
     *
     * @var string|null
     */
    protected $db2Version = null;

    /**
     * SQL expression for current timestamp
     *
     * @var string
     */
    protected string $nowExpression = 'CURRENT TIMESTAMP';

    /**
     * SQL function for string length
     *
     * @var string
     */
    protected string $lengthFunction = 'LENGTH';

    /**
     * SQL function for null coalescing
     *
     * @var string
     */
    protected string $ifNullFunction = 'COALESCE';

    /**
     * Constructs a new database object based on the given params
     *
     * @param   array  $options  The database connection params
     * @return  void
     * @throws  ConnectionFailedException  If the DSN is invalid or connection fails
     */
    public function __construct($options)
    {
        // Force lowercase column names for ORM compatibility.
        // DB2 returns UPPERCASE column names by default; CASE_LOWER normalizes them.
        // These go in 'extras' — Pdo::__construct() passes extras as the 4th PDO constructor arg.
        if (!isset($options['extras'])) {
            $options['extras'] = [];
        }
        $options['extras'][\PDO::ATTR_CASE] = \PDO::CASE_LOWER;

        // Establish connection string
        if (!isset($options['dsn'])) {
            if (isset($options['host']) && isset($options['database'])) {
                $host = $options['host'];
                $port = isset($options['port']) ? $options['port'] : '50000';
                $database = $options['database'];

                // pdo_ibm native format (no DRIVER= keyword — simpler and more compatible)
                // VALIDATE=RUN defers table validation to runtime instead of bind/prepare time
                // This is needed for DDL operations in transactions where tables may not exist yet at prepare time
                if (in_array('ibm', \PDO::getAvailableDrivers())) {
                    $options['dsn'] = "ibm:DATABASE={$database};"
                        . "HOSTNAME={$host};PORT={$port};"
                        . "PROTOCOL=TCPIP;VALIDATE=RUN";
                } else {
                    // ODBC fallback
                    $options['dsn'] = "odbc:DRIVER={IBM DB2 ODBC DRIVER};" .
                                      "DATABASE={$database};" .
                                      "HOSTNAME={$host};" .
                                      "PORT={$port};" .
                                      "PROTOCOL=TCPIP;" .
                                      "VALIDATE=RUN";
                }
            } elseif (isset($options['database'])) {
                // Cataloged database name
                if (in_array('ibm', \PDO::getAvailableDrivers())) {
                    $options['dsn'] = "ibm:{$options['database']}";
                } else {
                    $options['dsn'] = "odbc:{$options['database']}";
                }
            }
        }

        $validPrefixes = ['ibm:', 'odbc:'];
        $hasValidPrefix = false;
        foreach ($validPrefixes as $prefix) {
            if (isset($options['dsn']) && substr($options['dsn'], 0, strlen($prefix)) === $prefix) {
                $hasValidPrefix = true;
                break;
            }
        }

        if (!$hasValidPrefix) {
            throw new ConnectionFailedException('DB2 DSN for PDO connection does not appear to be valid.', 500);
        }

        // Call parent construct (creates lazy PdoConnection; no actual DB connection yet)
        parent::__construct($options);

        // Set syntax class name for query builder
        $this->syntax = 'db2';

        // Eagerly trigger the connection and apply DB2-specific attributes.
        // This mirrors the Informix driver pattern: calling setAttribute() forces
        // getPdo()->connect(), so that isConnected() returns true after construction.
        // Connection failures propagate naturally (caught by databaseProvider()).
        $this->setDb2Options();
    }

    /**
     * Sets DB2-specific connection options
     *
     * Calling setAttribute() on the PdoConnection triggers an eager connection
     * (getPdo() → connect()), which is required so that isConnected() returns
     * true and exec() can proceed. Connection failures are NOT caught here —
     * they propagate to the caller (typically databaseProvider()).
     *
     * @return  void
     */
    protected function setDb2Options(): void
    {
        // Apply ATTR_CASE after construction.
        // extras[] already has ATTR_CASE for the PDO constructor, but pdo_ibm
        // may not honor constructor options; setAttribute() ensures it takes effect.
        // Only catch \PDOException from setAttribute itself, not connection failures.
        try {
            $this->connection->setAttribute(\PDO::ATTR_CASE, \PDO::CASE_LOWER);
        } catch (\PDOException $e) {
            // setAttribute not supported — ATTR_CASE from extras[] will still apply
        }

        // Stringify LOBs automatically - pdo_ibm returns CLOB/BLOB columns as resources
        // This converts them to strings automatically when fetching
        try {
            $this->connection->setAttribute(\PDO::ATTR_STRINGIFY_FETCHES, true);
        } catch (\PDOException $e) {
            // setAttribute not supported
        }
    }

    /**
     * Override connect() to re-apply DB2-specific attributes
     *
     * After a new PDO connection is created, DB2-specific attributes
     * (ATTR_CASE, ATTR_STRINGIFY_FETCHES) must be re-applied.
     *
     * @return  void
     */
    public function connect(): void
    {
        parent::connect();

        if ($this->connection && $this->connection->isConnected()) {
            $this->setDb2Options();
        }
    }

    /**
     * Binds the given bindings to the prepared statement
     *
     * WORKAROUND for PDO_IBM bug: bindValue() with PDO::PARAM_NULL
     * causes "Unknown parameter type" error. Use PDO::PARAM_STR for
     * null values instead (which correctly inserts NULL).
     *
     * @param   array  $bindings  The param bindings
     * @param   array  $type      The param types (optional)
     * @return  $this
     */
    public function bind($bindings, $type = [])
    {
        $idx = 1;

        $this->bindings = $bindings;

        foreach ($bindings as $binding) {
            if (is_null($binding)) {
                // PDO_IBM bug: PARAM_NULL causes "Unknown parameter type" error
                // Use PARAM_STR which correctly inserts NULL
                $pdoType = \PDO::PARAM_STR;
            } elseif (is_bool($binding)) {
                $pdoType = \PDO::PARAM_BOOL;
            } elseif (is_int($binding)) {
                $pdoType = \PDO::PARAM_INT;
            } else {
                $pdoType = \PDO::PARAM_STR;
            }

            // Allow explicit type override
            if (isset($type[$idx])) {
                $pdoType = $this->translateType($type[$idx]);
            }

            $this->statement->bindValue($idx, $binding, $pdoType);
            $idx++;
        }

        return $this;
    }

    /**
     * Gets the name of the database in use by this connection
     *
     * Overrides the protected base-class method to make it publicly accessible.
     * Without this, Driver::__call() intercepts the call (empty args) and returns null.
     *
     * @return  string
     */
    public function getDatabase()
    {
        return $this->database;
    }

    /**
     * Prepare a SQL statement for execution
     *
     * DB2's pdo_ibm has issues with newlines in prepared statements - it treats
     * them as statement separators. Replace newlines with spaces before preparing.
     *
     * @param   string  $sql  The SQL statement to prepare
     * @return  $this
     */
    public function prepare($sql)
    {
        // Replace newlines with spaces for DB2 compatibility
        $sql = str_replace(["\r\n", "\r", "\n"], ' ', $sql);

        // Remove multiple consecutive spaces
        $sql = preg_replace('/\s+/', ' ', $sql);

        return parent::prepare($sql);
    }

    /**
     * Execute a non-query SQL statement (DDL, INSERT, UPDATE, DELETE)
     *
     * Wraps non-DDL statements in an implicit transaction to emulate
     * autocommit behavior. DDL statements are left unwrapped so the
     * PDO_IBM extension's native auto-commit handles them.
     *
     * @param   string  $statement  The SQL statement to execute
     * @return  int|false  Number of affected rows, or false on failure
     */
    public function exec($statement)
    {
        $isDdl = preg_match('/^\s*(CREATE|DROP|ALTER|TRUNCATE|RENAME)\s/i', $statement);

        if (!$isDdl && $this->connection && !$this->connection->inTransaction() && $this->transactionDepth == 0) {
            $this->connection->beginTransaction();
        }

        try {
            $result = parent::exec($statement);

            if (!$isDdl && $this->transactionDepth == 0 && $this->connection && $this->connection->inTransaction()) {
                $this->connection->commit();
            }

            return $result;
        } catch (\Exception $e) {
            if (!$isDdl && $this->transactionDepth == 0 && $this->connection && $this->connection->inTransaction()) {
                $this->connection->rollBack();
            }
            throw $e;
        }
    }

    /**
     * Execute a prepared statement
     *
     * Wraps non-DDL statements in an implicit transaction to emulate
     * autocommit behavior. DDL statements are left unwrapped so the
     * PDO_IBM extension's native auto-commit handles them.
     *
     * @return  mixed  For DELETE/UPDATE/INSERT: affected row count; otherwise $this
     */
    public function execute()
    {
        $sql = $this->statement ? $this->statement->queryString : '';
        $isDdl = $sql && preg_match('/^\s*(CREATE|DROP|ALTER|TRUNCATE|RENAME)\s/i', $sql);

        if (!$isDdl && $this->transactionDepth == 0 && $this->connection && !$this->connection->inTransaction()) {
            $this->connection->beginTransaction();
        }

        try {
            $result = parent::execute();

            if (!$isDdl && $this->transactionDepth == 0 && $this->connection && $this->connection->inTransaction()) {
                $this->connection->commit();
            }

            return $result;
        } catch (\Exception $e) {
            if (!$isDdl && $this->transactionDepth == 0 && $this->connection && $this->connection->inTransaction()) {
                $this->connection->rollBack();
            }
            throw $e;
        }
    }

    public function quoteName($name, $as = null)
    {
        // Uppercase each dot-separated part before delegating to base quoteName()
        if (strpos($name, '.') !== false) {
            $name = implode('.', array_map('strtoupper', explode('.', $name)));
        } else {
            $name = strtoupper($name);
        }

        return parent::quoteName($name, $as);
    }

    /**
     * Wrap table/column names with proper quoting and uppercasing
     *
     * DB2 stores unquoted identifiers as uppercase, so we must uppercase
     * before wrapping. This is used by JOIN queries.
     *
     * @param   string  $value  The table/column name or expression
     * @return  string
     */
    public function wrap($value)
    {
        $value = trim((string) $value);

        if ($value === '') {
            return '';
        }

        // Preserve derived-table expressions like "(SELECT ...)" as raw SQL
        if ($value[0] === '(' && substr($value, -1) === ')') {
            return $value;
        }

        // Handle explicit aliases: "table AS alias"
        if (preg_match('/^(.+)\s+as\s+([^\s]+)$/is', $value, $matches)) {
            return $this->wrap($matches[1]) . ' AS ' . $this->wrap($matches[2]);
        }

        // Handle shorthand alias: "table alias"
        if (preg_match('/^(.+)\s+([^\s]+)$/s', $value, $matches)) {
            return $this->wrap($matches[1]) . ' AS ' . $this->wrap($matches[2]);
        }

        // Uppercase and wrap each dot-separated part
        $quoted = [];
        $parts  = explode('.', $value);

        foreach ($parts as $part) {
            $part = trim($part);
            if ($part !== '*') {
                // Uppercase before wrapping (DB2 requirement)
                $quoted[] = sprintf($this->wrapper, strtoupper($part));
            } else {
                $quoted[] = $part;
            }
        }

        return implode('.', $quoted);
    }

    /**
     * Gets the database collation in use
     *
     * DB2 uses database territory and codeset for collation
     *
     * @return  string|bool
     */
    public function getCollation()
    {
        $this->setQuery(
            "SELECT COLLATION_SCHEMA || '.' || COLLATION_NAME"
            . " FROM SYSIBM.COLLATIONS"
            . " WHERE COLLATION_NAME = (SELECT CURRENT COLLATION FROM SYSIBM.SYSDUMMY1)"
        );
        try {
            $result = $this->loadResult();
            return $result ?: false;
        } catch (\Exception $e) {
            return false;
        }
    }

    /**
     * Shows the table CREATE statement that creates the given tables
     *
     * DB2 doesn't have SHOW CREATE TABLE; we reconstruct it from metadata
     *
     * @param   string|array  $tables  A table name or a list of table names
     * @return  array
     */
    public function getTableCreate($tables)
    {
        $result = [];

        foreach ((array) $tables as $table) {
            $tableName = $this->replacePrefix($table);
            $result[$table] = $this->generateCreateTableSql(strtoupper($tableName));
        }

        return $result;
    }

    /**
     * Generate a CREATE TABLE statement by introspecting the table structure
     *
     * @param   string  $table  The table name (uppercase, with prefix replaced)
     * @return  string  The CREATE TABLE SQL statement
     */
    protected function generateCreateTableSql(string $table): string
    {
        if (!$this->tableExists($table)) {
            return '';
        }

        $columns = $this->getTableColumns($table, false);
        $pk = $this->getPrimaryKey($table);

        $columnDefs = [];
        foreach ($columns as $name => $col) {
            $def = $this->quoteName($name) . ' ' . $col->Type;

            // NOT NULL
            if (isset($col->Null) && $col->Null === 'NO') {
                $def .= ' NOT NULL';
            }

            // DEFAULT value
            if (isset($col->Default) && $col->Default !== null) {
                $def .= ' DEFAULT ' . $col->Default;
            }

            $columnDefs[] = $def;
        }

        // Add primary key constraint
        if ($pk) {
            $pkColumns = is_array($pk) ? $pk : [$pk];
            $pkList = implode(', ', array_map([$this, 'quoteName'], $pkColumns));
            $columnDefs[] = 'PRIMARY KEY (' . $pkList . ')';
        }

        $sql = 'CREATE TABLE ' . $this->quoteName($table) . " (\n  ";
        $sql .= implode(",\n  ", $columnDefs);
        $sql .= "\n)";

        return $sql;
    }

    /**
     * Retrieves field information about the given table
     *
     * @param   string   $table     The name of the database table
     * @param   boolean  $typeOnly  True to only return field types
     * @return  array    An array of fields for the database table
     */
    public function getTableColumns($table, $typeOnly = true)
    {
        $result = [];
        $tableSub = strtoupper($this->replacePrefix($table));

        $this->setQuery("
            SELECT
                colname,
                typename || CASE
                    WHEN typename IN ('VARCHAR', 'CHARACTER', 'CHAR', 'VARGRAPHIC', 'GRAPHIC')
                    THEN '(' || length || ')'
                    WHEN typename IN ('DECIMAL', 'NUMERIC')
                    THEN '(' || length || ',' || scale || ')'
                    ELSE ''
                END AS data_type_full,
                nulls,
                \"DEFAULT\" AS col_default
            FROM syscat.columns
            WHERE tabname = " . $this->quote($tableSub) . "
            ORDER BY colno
        ");

        $fields = $this->loadObjectList();

        if ($typeOnly) {
            foreach ($fields as $field) {
                // DB2 returns column names in uppercase; normalize to lowercase for consistency
                $result[strtolower($field->colname)] = strtolower($field->data_type_full);
            }
        } else {
            foreach ($fields as $field) {
                // pdo_ibm may return the DEFAULT value as a resource (LOB stream).
                $defaultVal = $field->col_default ?? null;
                if (is_resource($defaultVal)) {
                    $defaultVal = stream_get_contents($defaultVal) ?: '';
                }

                // DB2 returns column names in uppercase; normalize to lowercase for consistency
                $colname = strtolower($field->colname);
                $result[$colname] = (object) [
                    'Default' => trim((string) ($defaultVal ?? '')),
                    'Comment' => '',
                    'Field'   => $colname,
                    'Type'    => strtolower($field->data_type_full),
                    'Null'    => $field->nulls === 'Y' ? 'YES' : 'NO'
                ];
            }
        }

        return $result;
    }

    /**
     * Get the details list of keys for a table
     *
     * @param   string  $table  The name of the table
     * @return  array   An array of the column specification for the table
     */
    public function getTableKeys($table)
    {
        $tableSub = strtoupper($this->replacePrefix($table));

        $this->setQuery("
            SELECT
                CASE WHEN i.uniquerule = 'P' THEN 'PRIMARY' ELSE LOWER(i.indname) END AS Key_name,
                CASE WHEN i.uniquerule IN ('U', 'P') THEN 0 ELSE 1 END AS Non_unique,
                LOWER(ic.colname) AS Column_name,
                ic.colseq AS Seq_in_index,
                'BTREE' AS Index_type
            FROM syscat.indexes i
            JOIN syscat.indexcoluse ic ON i.indschema = ic.indschema AND i.indname = ic.indname
            WHERE i.tabname = " . $this->quote($tableSub) . "
            AND i.tabschema = CURRENT SCHEMA
            ORDER BY CASE WHEN i.uniquerule = 'P' THEN 0 ELSE 1 END, i.indname, ic.colseq
        ");

        $rows = $this->loadObjectList();

        // Group by key_name (lowercase due to ATTR_CASE = CASE_LOWER)
        // But SchemaManager expects uppercase property names, so convert
        $grouped = [];
        foreach ($rows as $row) {
            // Properties are lowercase due to ATTR_CASE, but SchemaManager expects uppercase
            // Convert to uppercase property names
            $fixedRow = (object)[
                'Key_name' => $row->key_name,
                'Non_unique' => $row->non_unique,
                'Column_name' => $row->column_name,
                'Seq_in_index' => $row->seq_in_index,
                'Index_type' => $row->index_type,
            ];

            $keyName = $row->key_name;
            if (!isset($grouped[$keyName])) {
                $grouped[$keyName] = [];
            }
            $grouped[$keyName][] = $fixedRow;
        }

        return $grouped;
    }

    /**
     * Gets all indexes for a table with their columns and properties
     *
     * @param   string  $table  The table name
     * @return  array   Array of index objects
     */
    public function getIndexes($table)
    {
        $tableSub = strtoupper($this->replacePrefix($table));

        $this->setQuery("
            SELECT
                LOWER(i.indname) AS index_name,
                CASE WHEN i.uniquerule = 'P' THEN 1 ELSE 0 END AS is_primary,
                CASE WHEN i.uniquerule IN ('U', 'P') THEN 1 ELSE 0 END AS is_unique,
                LOWER(ic.colname) AS column_name,
                ic.colseq
            FROM syscat.indexes i
            JOIN syscat.indexcoluse ic
                ON i.indschema = ic.indschema AND i.indname = ic.indname
            WHERE i.tabname = " . $this->quote($tableSub) . "
            AND i.tabschema = CURRENT SCHEMA
            ORDER BY i.indname, ic.colseq
        ");

        $rows = $this->loadObjectList();
        $indexes = [];

        foreach ($rows as $row) {
            $isPrimary = (int) $row->is_primary;
            $name = $isPrimary
                ? 'PRIMARY'
                : $row->index_name;  // Already lowercase from query

            if (!isset($indexes[$name])) {
                $indexes[$name] = (object) [
                    'name'    => $name,
                    'columns' => [],
                    'unique'  => (bool) $row->is_unique,
                    'primary' => (bool) $isPrimary,
                ];
            }

            $indexes[$name]->columns[] = $row->column_name;  // Already lowercase from query
        }

        return array_values($indexes);
    }

    /**
     * Returns whether or not the given table exists
     *
     * @param   string  $table  A table name (with or without prefix)
     * @return  bool
     */
    public function tableExists($table)
    {
        $table = strtoupper($this->replacePrefix($table));
        $tables = $this->getTableList();

        return in_array($table, array_map('strtoupper', $tables), true);
    }

    /**
     * Gets an array of all tables in the database
     *
     * @return  array
     */
    public function getTableList()
    {
        $this->setQuery(
            "SELECT tabname FROM syscat.tables"
            . " WHERE tabschema = CURRENT SCHEMA AND type = 'T'"
            . " ORDER BY tabname"
        );
        $tables = $this->loadColumn();
        // Normalize to lowercase for consistency with other drivers
        return array_map('strtolower', $tables);
    }

    /**
     * Locks a table in the database
     *
     * @param   string  $tableName  The name of the table to lock
     * @return  $this
     */
    public function lockTable($tableName)
    {
        $this->setQuery('LOCK TABLE ' . $this->quoteName($tableName) . ' IN EXCLUSIVE MODE');
        $this->execute();

        return $this;
    }

    /**
     * Renames a table in the database
     *
     * @param   string  $oldTable  The name of the table to be renamed
     * @param   string  $newTable  The new name for the table
     * @param   string  $backup    Table prefix (unused)
     * @param   string  $prefix    For the table (unused)
     * @return  $this
     * @throws  \RuntimeException  If the source table does not exist
     */
    public function renameTable($oldTable, $newTable, $backup = null, $prefix = null)
    {
        $oldTable = strtoupper($this->replacePrefix($oldTable));
        $newTable = strtoupper($this->replacePrefix($newTable));

        if (!$this->tableExists($oldTable)) {
            throw new \RuntimeException('Table not found in DB2 database.');
        }

        $this->setQuery('RENAME TABLE ' . $this->quoteName($oldTable) . ' TO ' . $this->quoteName($newTable));
        $this->execute();

        return $this;
    }

    /**
     * Selects a database for use
     *
     * DB2 doesn't support database switching; each connection is to a specific database.
     * You can change the current schema with SET SCHEMA.
     *
     * @param   string  $database  The name of the database (schema) to select
     * @return  bool
     */
    public function select($database)
    {
        try {
            $this->setQuery('SET SCHEMA ' . $this->quoteName(strtoupper($database)));
            $this->execute();
            return true;
        } catch (\Exception $e) {
            return false;
        }
    }

    /**
     * Gets the database engine of the given table
     *
     * DB2 doesn't have storage engines like MySQL
     *
     * @param   string       $table  The table for which to retrieve the engine type
     * @return  string|bool
     */
    public function getEngine($table)
    {
        return 'DB2';
    }


    /**
     * Gets the database character set of the given table
     *
     * DB2 uses database codeset
     *
     * @param   string       $table  The table for which to retrieve the character set (ignored)
     * @param   string       $field  The field to check (ignored)
     * @return  string|bool
     */
    public function getCharacterSet($table, $field = null)
    {
