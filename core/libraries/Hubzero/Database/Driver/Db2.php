    /**
     * Get CHECK constraints for table
     *
     * @param   string  $table  Table name
     * @return  array
     */
    public function getCheckConstraints(string $table): array
    {
        $table = strtoupper($this->replacePrefix($table));

        $sql = "SELECT 
                   constname AS name,
                   text AS expression
                FROM syscat.checks
                WHERE tabname = " . $this->quote($table);

        $this->setQuery($sql);
        $results = $this->loadObjectList();

        $constraints = [];
        foreach ($results as $row) {
            $constraints[] = (object) [
                'name' => trim($row->name),
                'expression' => trim($row->expression)
            ];
        }

        return $constraints;
    }

    /**
     * Add stored (computed) column
     *
     * DB2 uses GENERATED ALWAYS AS (...)
     *
     * @param   string       $table       Table name
     * @param   string       $column      Column name
     * @param   string       $expression  SQL expression
     * @param   string|null  $type        Column type (ignored by DB2)
     * @return  bool
     */
    public function addStoredColumn(string $table, string $column, string $expression, ?string $type = null): bool
    {
        $table = $this->replacePrefix($table);
        $column = $this->quoteName($column);
        $this->setQuery("ALTER TABLE $table ADD $column GENERATED ALWAYS AS ($expression)");
        return $this->execute();
