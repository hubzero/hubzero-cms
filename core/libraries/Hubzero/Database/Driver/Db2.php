    /**
     * Drop the primary key from a table
     *
     * @param   string  $table  Table name
     * @return  bool
     */
    public function dropPrimaryKey(string $table): bool
    {
        $table = strtoupper($this->replacePrefix($table));

        if (!$this->tableExists($table)) {
            return false;
        }

        // Find the primary key constraint name
        $this->setQuery(
            "SELECT constname FROM syscat.tabconst"
            . " WHERE tabname = " . $this->quote($table)
            . " AND type = 'P' AND tabschema = CURRENT SCHEMA"
        );
        $constraintName = $this->loadResult();

        if (!$constraintName) {
            return true; // No primary key
        }

        $query = 'ALTER TABLE ' . $this->quoteName($table) . ' DROP PRIMARY KEY';
        $this->setQuery($query);
        return (bool) $this->execute();
    }

    /**
     * Add a primary key to a table
     *
     * @param   string        $table    Table name
     * @param   string|array  $columns  Column name(s)
     * @return  bool
     */
    public function addPrimaryKey(string $table, $columns): bool
    {
        $table = strtoupper($this->replacePrefix($table));

        if (!$this->tableExists($table)) {
            return false;
        }

        $columns = is_array($columns) ? $columns : [$columns];

        // DB2 requires primary key columns to be NOT NULL
        // First, ensure all columns are NOT NULL
        foreach ($columns as $column) {
            $quotedColumn = $this->quoteName(strtoupper($column));
            $quotedTable = $this->quoteName($table);

            // Get column info to check current type
            $columnInfo = $this->getTableColumns($table, false);
            if (!isset($columnInfo[strtolower($column)])) {
                return false;
            }

            $colInfo = $columnInfo[strtolower($column)];
            $type = $colInfo->Type ?? 'VARCHAR(255)';

            // Set column to NOT NULL if it isn't already
            if ($colInfo->Null !== 'NO') {
                $alterQuery = "ALTER TABLE $quotedTable ALTER COLUMN $quotedColumn SET NOT NULL";
                $this->setQuery($alterQuery);
                try {
                    $this->execute();
                } catch (\Exception $e) {
                    // If column contains NULLs, this will fail
                    return false;
                }
            }
        }

        $columnList = implode(', ', array_map(function ($col) {
            return $this->quoteName(strtoupper($col));
        }, $columns));

        $query = 'ALTER TABLE ' . $this->quoteName($table) . ' ADD PRIMARY KEY (' . $columnList . ')';
        $this->setQuery($query);
        return (bool) $this->execute();
    }

    /**
     * Add an auto-increment primary key column to a table
     *
     * DB2 uses IDENTITY columns for auto-increment behavior
     *
     * @param   string  $table      Table name
     * @param   string  $column     Column name
     * @param   bool    $first      Add as first column (ignored)
     * @param   bool    $useBigInt  Use BIGINT for large values
     * @return  bool
     */
    public function addAutoIncrementPrimaryKey(
        string $table,
        string $column = 'id',
        bool $first = false,
        bool $useBigInt = true
    ): bool {
        $table = strtoupper($this->replacePrefix($table));
        $column = strtoupper($column);

        if (!$this->tableExists($table)) {
            return false;
        }

        if ($this->tableHasField($table, $column)) {
            return true;
        }

        $type = $useBigInt ? 'BIGINT' : 'INTEGER';
        $quotedTable = $this->quoteName($table);
        $quotedColumn = $this->quoteName($column);

        // DB2 doesn't support adding IDENTITY property via ALTER TABLE ADD COLUMN
        // Use multi-step approach for all cases

        // 1. Add nullable integer column
        $query = "ALTER TABLE {$quotedTable} ADD COLUMN {$quotedColumn} {$type}";
        $this->setQuery($query);
        if (!$this->execute()) {
            return false;
        }

        // 2. Check if table has rows and populate if needed
        $this->setQuery("SELECT COUNT(*) FROM {$quotedTable}");
        $rowCount = (int) $this->loadResult();

        if ($rowCount > 0) {
            // Populate with sequential values
            if (!$this->populateSequentialValues($table, $column)) {
                return false;
            }
        } else {
            // Empty table: set default for future inserts
            // Note: We can't add IDENTITY after the fact in ALTER TABLE
            // Column will need explicit values or application-level sequence
        }

        // 3. Make column NOT NULL
        $query = "ALTER TABLE {$quotedTable} ALTER COLUMN {$quotedColumn} SET NOT NULL";
        $this->setQuery($query);
        $result = (bool) $this->execute();

        if ($result) {
            // Add primary key constraint
            $this->addPrimaryKey($table, $column);
        }

        return $result;
    }

    /**
     * Populate a column with sequential integer values
     *
     * @param   string       $table    Table name
     * @param   string       $column   Column name
     * @param   string|null  $orderBy  Optional column to order by
     * @return  bool
     */
    public function populateSequentialValues(string $table, string $column, ?string $orderBy = null): bool
    {
        $table = strtoupper($this->replacePrefix($table));
        $column = strtoupper($column);

        if (!$this->tableExists($table) || !$this->tableHasField($table, $column)) {
            return false;
        }

        $quotedTable = $this->quoteName($table);
        $quotedColumn = $this->quoteName($column);
        $orderClause = $orderBy ? $this->quoteName(strtoupper($orderBy)) : $quotedColumn;

        // Use MERGE with ROW_NUMBER()
        $query = "MERGE INTO {$quotedTable} t " .
                 "USING (SELECT RID_BIT(t2) AS rid, " .
                 "ROW_NUMBER() OVER (ORDER BY {$orderClause}) AS rn " .
                 "FROM {$quotedTable} t2) s " .
                 "ON (RID_BIT(t) = s.rid) " .
                 "WHEN MATCHED THEN UPDATE SET t.{$quotedColumn} = s.rn";

        $this->setQuery($query);
        return (bool) $this->execute();
    }

    /**
     * Gets the primary key of a table
     *
     * @param   string  $table  The table name
