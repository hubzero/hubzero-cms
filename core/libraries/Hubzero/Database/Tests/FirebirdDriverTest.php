/**
 * Firebird-specific driver tests
 *
 * Runs against all configured backends via the standard databaseProvider.
 * Tests that receive a non-Firebird driver pass with a no-op assertion.
 * If multiple Firebird instances are configured (e.g. Firebird 3 and 4),
 * each test runs against all of them.
 *
 * Configuration: Add 'firebird' to DB_TEST_BACKENDS and set DB_FIREBIRD_*
 * credentials in phpunit.xml or via environment variables.
 */
#[Group('firebird')]
#[Group('database')]
