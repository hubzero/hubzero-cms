    protected static function getTestTables(): array
    {
        return ['FT_ITEMS', 'FT_CATEGORIES'];
    }

    protected static function setUpDatabase(Driver $driver): void
    {
        if (get_class($driver) !== Firebird::class) {
            return;
        }

        // Drop in correct order (view depends on table, child depends on parent)
        foreach (['FT_ACTIVE_ITEMS'] as $view) {
            try {
                $driver->exec("DROP VIEW $view");
            } catch (\Exception $e) {
            }
        }
        foreach (['FT_ITEMS', 'FT_CATEGORIES'] as $table) {
            try {
                $driver->dropTable($table, true);
            } catch (\Exception $e) {
            }
        }

        $driver->exec('
            CREATE TABLE FT_CATEGORIES (
                ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                NAME VARCHAR(100) NOT NULL,
                SLUG VARCHAR(100),
                SORT_ORDER INTEGER DEFAULT 0,
                ACTIVE SMALLINT DEFAULT 1,
                CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        ');

        $driver->exec('
            CREATE TABLE FT_ITEMS (
                ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                CATEGORY_ID INTEGER,
                TITLE VARCHAR(200) NOT NULL,
                DESCRIPTION BLOB SUB_TYPE TEXT,
                PRICE DECIMAL(10,2) DEFAULT 0.00,
                STOCK INTEGER DEFAULT 0,
                STATUS VARCHAR(20) DEFAULT \'active\',
                CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                CONSTRAINT FK_ITEMS_CAT FOREIGN KEY (CATEGORY_ID)
                    REFERENCES FT_CATEGORIES(ID) ON DELETE SET NULL
            )
        ');

        $driver->exec('CREATE INDEX IDX_ITEMS_STATUS ON FT_ITEMS (STATUS)');
        $driver->exec('CREATE INDEX IDX_ITEMS_CAT ON FT_ITEMS (CATEGORY_ID)');

        $driver->exec("INSERT INTO FT_CATEGORIES (NAME, SLUG, SORT_ORDER) VALUES ('Electronics', 'electronics', 1)");
        $driver->exec("INSERT INTO FT_CATEGORIES (NAME, SLUG, SORT_ORDER) VALUES ('Books', 'books', 2)");
        $driver->exec(
            "INSERT INTO FT_CATEGORIES (NAME, SLUG, SORT_ORDER, ACTIVE) VALUES ('Archived', 'archived', 99, 0)"
        );

        $driver->exec(
            "INSERT INTO FT_ITEMS (CATEGORY_ID, TITLE, PRICE, STOCK, STATUS) VALUES (1, 'Laptop', 999.99, 10, 'active')"
        );
        $driver->exec(
            "INSERT INTO FT_ITEMS (CATEGORY_ID, TITLE, PRICE, STOCK, STATUS) VALUES (1, 'Phone', 599.99, 25, 'active')"
        );
        $driver->exec(
            "INSERT INTO FT_ITEMS (CATEGORY_ID, TITLE, PRICE, STOCK, STATUS) VALUES (2, 'Novel', 19.99, 100, 'active')"
        );
        $driver->exec(
            "INSERT INTO FT_ITEMS (CATEGORY_ID, TITLE, PRICE, STOCK, STATUS) VALUES (2, 'Textbook', 79.99, 5, 'draft')"
        );
    }

    /**
     * Check if the driver is Firebird; if not, pass with no-op assertion.
     */
    private function requiresFirebird(Driver $driver): bool
    {
        if (get_class($driver) !== Firebird::class) {
            $this->assertTrue(true);
            return false;
        }
        return true;
    }

    protected function tearDown(): void
    {
        parent::tearDown();

        // Clean up ad-hoc tables created by individual migration tests
        $migTables = [
            'MIG_ADD_PK', 'MIG_IDEMPOTENT', 'MIG_CUSTOM_PK',
            'MIG_COMPLEX', 'MIG_RESOURCE_ASSOC', 'MIG_DROP_COL',
            'MIG_ADD_COL', 'MIG_INDEX_TEST', 'MIG_FK_CHILD', 'MIG_FK_PARENT',
            'MIG_TRUNCATE', 'MIG_VARCHAR_LEN', 'MIG_INT_BIGINT',
            'MIG_DEFAULTS', 'MIG_NOTNULL',
            'MIG_VIEW_CRE', 'MIG_VIEW_REP', 'MIG_VIEW_EXI', 'MIG_VIEW_DRO'
        ];

        $migGenerators = [
            'GEN_MIG_ADD_PK_ID', 'GEN_MIG_CUSTOM_PK_ID',
            'GEN_MIG_COMPLEX_ID', 'GEN_MIG_RESOURCE_ASSOC_ID'
        ];

        $migViews = ['MIG_TEST_VIEW_CRE', 'MIG_REPLACE_VIEW', 'MIG_EXISTS_VIEW', 'MIG_DROP_VIEW'];

        foreach (static::getClassDrivers() as $driver) {
            if (get_class($driver) !== Firebird::class) {
                continue;
            }
            foreach ($migViews as $view) {
                try {
                    $driver->exec("DROP VIEW $view");
                } catch (\Exception $e) {
                }
            }
            foreach ($migTables as $table) {
                try {
                    $driver->exec("DROP TABLE $table");
                } catch (\Exception $e) {
                }
            }
            foreach ($migGenerators as $gen) {
                try {
                    $driver->exec("DROP GENERATOR $gen");
                } catch (\Exception $e) {
                }
            }
        }
    }

    public static function tearDownAfterClass(): void
    {
        // Drop views before parent drops the base tables they depend on
        foreach (static::getClassDrivers() as $driver) {
            if (get_class($driver) !== Firebird::class) {
                continue;
            }
            try {
                $driver->exec('DROP VIEW FT_ACTIVE_ITEMS');
            } catch (\Exception $e) {
            }
        }

        parent::tearDownAfterClass();
    }

