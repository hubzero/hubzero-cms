    #[Test]
    #[DataProvider('databaseProvider')]
    public function canRollbackTransaction(string $dbName, Driver $driver): void
    {
        if (!$this->requiresFirebird($driver)) {
            return;
        }

        // Separate connection to test isolation
        $config = static::$testDatabases[$dbName];
        $driver2 = new Firebird($config);
        $driver2->connect();

        $driver2->transactionStart();
        $driver2->exec("INSERT INTO FT_CATEGORIES (NAME, SLUG) VALUES ('Trans Rollback', 'trans-rollback')");
        $driver2->transactionRollback();

        $driver->setQuery("SELECT COUNT(*) FROM FT_CATEGORIES WHERE SLUG = 'trans-rollback'");
        $count = (int) $driver->loadResult();

        $driver->exec("DELETE FROM FT_CATEGORIES WHERE SLUG = 'trans-rollback'");
        $driver2->disconnect();

        $this->assertEquals(0, $count, 'Rolled back row should not be visible');
    }

