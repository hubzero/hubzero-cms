    protected static function setUpDatabase(Driver $driver): void
    {
        if (get_class($driver) !== Oci::class) {
            return;
        }

        // Drop in FK-safe order
        foreach (['ora_items', 'ora_categories'] as $table) {
            try {
                $driver->dropTable($table, true);
            } catch (\Exception $e) {
            }
        }

        $driver->exec("
            CREATE TABLE ora_categories (
                id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR2(100) NOT NULL,
                slug VARCHAR2(100),
                sort_order NUMBER(10) DEFAULT 0,
                active NUMBER(1) DEFAULT 1,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        ");

        $driver->exec("
            CREATE TABLE ora_items (
                id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                category_id NUMBER(10),
                title VARCHAR2(200) NOT NULL,
                description CLOB,
                price NUMBER(10,2) DEFAULT 0.00,
                stock NUMBER(10) DEFAULT 0,
                status VARCHAR2(20) DEFAULT 'active',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                CONSTRAINT fk_ora_items_cat FOREIGN KEY (category_id)
                    REFERENCES ora_categories(id) ON DELETE SET NULL
            )
        ");

        $driver->exec(
            "CREATE INDEX idx_ora_items_status ON ora_items (status)"
        );

        $driver->exec(
            "INSERT INTO ora_categories (name, slug, sort_order)"
            . " VALUES ('Electronics', 'electronics', 1)"
        );
        $driver->exec(
            "INSERT INTO ora_categories (name, slug, sort_order)"
            . " VALUES ('Books', 'books', 2)"
        );
        $driver->exec(
            "INSERT INTO ora_categories (name, slug, sort_order, active)"
            . " VALUES ('Archived', 'archived', 99, 0)"
        );

        $driver->exec(
            "INSERT INTO ora_items (category_id, title, price, stock, status)"
            . " VALUES (1, 'Laptop', 999.99, 10, 'active')"
        );
        $driver->exec(
            "INSERT INTO ora_items (category_id, title, price, stock, status)"
            . " VALUES (1, 'Phone', 599.99, 25, 'active')"
        );
        $driver->exec(
            "INSERT INTO ora_items (category_id, title, price, stock, status)"
            . " VALUES (2, 'Novel', 19.99, 100, 'active')"
        );
        $driver->exec(
            "INSERT INTO ora_items (category_id, title, price, stock, status)"
            . " VALUES (2, 'Textbook', 79.99, 5, 'draft')"
        );
    }

    private function requiresOracle(Driver $driver): bool
    {
        if (get_class($driver) !== Oci::class) {
            $this->assertTrue(true);
            return false;
        }
        return true;
    }

    protected function tearDown(): void
    {
        parent::tearDown();

        $adHocViews = ['ora_test_view', 'ora_active_items'];
        $adHocTables = [
            'ora_rename_dest', 'ora_rename_src',
            'ora_fk_child', 'ora_fk_parent',
            'ora_ddl_test', 'ora_trunc_test',
            'ora_identity_test', 'ora_view_src',
            'ora_pk_test',
        ];
        $adHocSequences = ['ora_test_seq'];

        foreach (static::getClassDrivers() as $driver) {
            if (get_class($driver) !== Oci::class) {
                continue;
            }
            foreach ($adHocViews as $view) {
                try {
                    $driver->dropView($view, true);
                } catch (\Exception $e) {
                }
            }
            foreach ($adHocTables as $table) {
                try {
                    $driver->dropTable($table, true);
                } catch (\Exception $e) {
                }
            }
            foreach ($adHocSequences as $seq) {
                try {
                    $driver->dropSequence($seq, true);
                } catch (\Exception $e) {
                }
            }
        }
    }

