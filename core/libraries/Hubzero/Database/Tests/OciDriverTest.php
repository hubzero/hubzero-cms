    #[Test]
    #[DataProvider('databaseProvider')]
    public function oracleGrammarDelegationMatchesGenericCreateCompilation(string $dbName, Driver $driver): void
    {
        if (!$this->requiresOracle($driver)) {
            return;
        }

        $fallbackGrammar = new class ($driver) extends \Hubzero\Database\Schema\Grammars\OciGrammar {
            public function compileCreateTableFromDefinition(array $definition): array
            {
                return parent::compileCreateTableFromDefinition($definition);
            }
        };

        $delegated = new TableBuilder($driver, 'parity_oracle_items');
        $delegated->id()
            ->string('name', 80)
            ->integer('status')->default(1)
            ->index('idx_name', 'name')
            ->uniqueIndex('uidx_name', 'name')
            ->foreign('group_id', 'parity_groups', 'id', 'CASCADE', 'RESTRICT')
            ->ifNotExists(false);

        $fallback = new class ($driver, 'parity_oracle_items', $fallbackGrammar) extends TableBuilder {
            private \Hubzero\Database\Schema\Grammar $grammar;

            public function __construct(
                Driver $driver,
                string $table,
                \Hubzero\Database\Schema\Grammar $grammar
            ) {
                parent::__construct($driver, $table);
                $this->grammar = $grammar;
            }

            protected function getGrammar()
            {
                return $this->grammar;
            }
        };

        $fallback->id()
            ->string('name', 80)
            ->integer('status')->default(1)
            ->index('idx_name', 'name')
            ->uniqueIndex('uidx_name', 'name')
            ->foreign('group_id', 'parity_groups', 'id', 'CASCADE', 'RESTRICT')
            ->ifNotExists(false);

        $this->assertSame($fallback->toSqlStatements(), $delegated->toSqlStatements());
    }

