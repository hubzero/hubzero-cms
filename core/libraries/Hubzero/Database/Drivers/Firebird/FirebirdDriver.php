    /**
     * Renames a table
     *
     * @param   string  $oldTable  The old table name
     * @param   string  $newTable  The new table name
     * @param   string  $backup    Backup prefix (unused)
     * @param   string  $prefix    Table prefix (unused)
     * @return  $this
     */
    public function renameTable($oldTable, $newTable, $backup = null, $prefix = null)
    {
        $oldTable = strtoupper($this->replacePrefix($oldTable));
        $newTable = strtoupper($this->replacePrefix($newTable));

        // Firebird doesn't have a direct RENAME TABLE command.
        // We implement it by: 1) Create new table, 2) Copy data, 3) Recreate constraints/indexes, 4) Drop old table

        // Step 1: Verify table exists first
        if (!$this->tableExists($oldTable)) {
            throw new \RuntimeException("Table '$oldTable' does not exist");
        }

        // Step 2: Get full column definitions
        $columns = $this->getTableColumnDefinitions($oldTable);
        if (empty($columns)) {
            throw new \RuntimeException(
                "PDO_FIREBIRD MVCC metadata visibility limitation: Table '$oldTable' exists but " .
                "getTableColumnDefinitions() returned no columns. This is a known issue where " .
                "Firebird's MVCC architecture prevents the JOIN between RDB\$RELATION_FIELDS and " .
                "RDB\$FIELDS from seeing recently committed DDL metadata, even after reconnecting. " .
                "See getTableColumnDefinitions() diagnostic output for details."
            );
        }

        // Step 2: Get primary key
        $primaryKey = $this->getPrimaryKey($oldTable);
        $pkColumns = $primaryKey ? $this->getPrimaryKeyColumns($oldTable) : [];

        // Step 3: Get indexes (excluding primary key index)
        $indexes = $this->getIndexes($oldTable);

        // Step 4: Get foreign keys on this table
        $foreignKeys = $this->getForeignKeys($oldTable);

        // Step 5: Check for associated generator (auto-increment)
        $generator = $this->findTableGenerator($oldTable);
        $generatorValue = null;
        if ($generator) {
            $generatorValue = $this->getGeneratorValue($generator);
        }

        // Step 6: Create new table with column definitions
        $columnDefs = [];
        foreach ($columns as $col) {
            $def = $this->quoteName($col->name) . ' ' . $col->fullType;
            if (!$col->nullable) {
                $def .= ' NOT NULL';
            }
            if ($col->default !== null) {
                $def .= ' DEFAULT ' . $col->default;
            }
            $columnDefs[] = $def;
        }

        // Add primary key constraint if exists
        if (!empty($pkColumns)) {
            $pkColNames = array_map([$this, 'quoteName'], $pkColumns);
            $columnDefs[] = 'PRIMARY KEY (' . implode(', ', $pkColNames) . ')';
        }

        $createSql = 'CREATE TABLE ' . $this->quoteName($newTable) . ' (' . implode(', ', $columnDefs) . ')';
        $this->setQuery($createSql);
        $this->execute();

        // Step 7: Copy data from old table to new table
        $colNames = array_map(function ($col) {
            return $this->quoteName($col->name);
        }, $columns);
        $copySql = 'INSERT INTO ' . $this->quoteName($newTable) . ' (' . implode(', ', $colNames) . ') ' .
                   'SELECT ' . implode(', ', $colNames) . ' FROM ' . $this->quoteName($oldTable);
        $this->setQuery($copySql);
        $this->execute();

        // Step 8: Create new generator if one existed
        if ($generator) {
            $newGenerator = 'GEN_' . $newTable . '_ID';
            try {
                $this->setQuery('CREATE GENERATOR ' . $this->quoteName($newGenerator));
                $this->execute();
                if ($generatorValue !== null) {
                    $this->setQuery(
                        'SET GENERATOR ' . $this->quoteName($newGenerator)
                        . ' TO ' . (int) $generatorValue
                    );
                    $this->execute();
                }

                // Create trigger for auto-increment on new table
                $triggerName = 'TRG_' . $newTable . '_BI';
                $pkCol = !empty($pkColumns) ? $pkColumns[0] : 'ID';
                $this->setQuery(
                    "CREATE TRIGGER " . $this->quoteName($triggerName)
                    . " FOR " . $this->quoteName($newTable)
                    . " ACTIVE BEFORE INSERT POSITION 0"
                    . " AS BEGIN"
                    . " IF (NEW." . $this->quoteName($pkCol)
                    . " IS NULL OR NEW." . $this->quoteName($pkCol)
                    . " = 0) THEN"
                    . " NEW." . $this->quoteName($pkCol)
                    . " = GEN_ID(" . $this->quoteName($newGenerator) . ", 1);"
                    . " END"
                );
                $this->execute();
            } catch (\Exception $e) {
                // Continue even if generator/trigger creation fails
            }
        }

        // Step 9: Recreate indexes on new table
        foreach ($indexes as $index) {
            // Skip primary key indexes (already created with table)
            if (stripos($index->name, 'PK_') === 0 || stripos($index->name, 'RDB$PRIMARY') === 0) {
                continue;
            }

            $newIndexName = str_replace($oldTable, $newTable, $index->name);
            $indexCols = array_map([$this, 'quoteName'], $index->columns);
            $unique = $index->unique ? 'UNIQUE ' : '';

            try {
                $this->setQuery('CREATE ' . $unique . 'INDEX ' . $this->quoteName($newIndexName) .
                               ' ON ' . $this->quoteName($newTable) . ' (' . implode(', ', $indexCols) . ')');
                $this->execute();
            } catch (\Exception $e) {
                // Continue even if index creation fails
            }
        }

        // Step 10: Recreate foreign keys on new table
        foreach ($foreignKeys as $fk) {
            $newFkName = str_replace($oldTable, $newTable, $fk->name);
            $fkCols = array_map([$this, 'quoteName'], $fk->columns);
            $refCols = array_map([$this, 'quoteName'], $fk->foreign_columns);

            try {
                $this->setQuery('ALTER TABLE ' . $this->quoteName($newTable) .
                               ' ADD CONSTRAINT ' . $this->quoteName($newFkName) .
                               ' FOREIGN KEY (' . implode(', ', $fkCols) . ')' .
                               ' REFERENCES ' . $this->quoteName($fk->foreign_table) .
                               ' (' . implode(', ', $refCols) . ')');
                $this->execute();
            } catch (\Exception $e) {
                // Continue even if FK creation fails
            }
        }

        // Step 11: Drop old table (this also drops old generator trigger and indexes)
        $this->dropTable($oldTable, false);

        // Step 12: Drop old generator if it existed
        if ($generator) {
            try {
                $this->setQuery('DROP GENERATOR ' . $this->quoteName($generator));
                $this->execute();
            } catch (\Exception $e) {
                // Ignore if generator doesn't exist
            }
        }

        return $this;
    }

    /**
     * Get detailed column definitions for table recreation
     *
     * Firebird MVCC (Multi-Generational Architecture) means transactions see a snapshot
     * of the database from when they started. To ensure we see the latest metadata changes,
     * we commit any implicit transaction and start a fresh one before querying system tables.
     *
     * @param   string  $table  The table name
     * @return  array   Array of column definition objects
     */
    protected function getTableColumnDefinitions($table)
    {
        $table = strtoupper($this->replacePrefix($table));
        $columns = [];

        // Firebird MVCC metadata visibility workaround:
        // Firebird's Multi-Version Concurrency Control means transactions see a snapshot
        // from when they started. Even after DDL changes are committed, the current
        // connection may not see updated metadata in system tables (RDB$RELATION_FIELDS).
        //
        // Reconnecting is the most reliable solution - it creates a fresh connection
        // that sees all committed changes. Only reconnect if not in a transaction.
        if ($this->transactionDepth == 0) {
            $this->reconnect();
        }

        // IMPORTANT: Run diagnostics AFTER reconnect to see what the new connection sees
        // Diagnostic: Check if table exists in RDB$RELATIONS
        $this->setQuery("SELECT COUNT(*) FROM RDB\$RELATIONS WHERE RDB\$RELATION_NAME = " . $this->quote($table));
        $tableExists = (int) $this->loadResult();

        // Diagnostic: Check if fields exist in RDB$RELATION_FIELDS
        $this->setQuery("SELECT COUNT(*) FROM RDB\$RELATION_FIELDS WHERE RDB\$RELATION_NAME = " . $this->quote($table));
        $fieldCount = (int) $this->loadResult();

        // Diagnostic: Check if the issue is with the JOIN to RDB$FIELDS
        $this->setQuery(
            "SELECT TRIM(RDB\$FIELD_SOURCE) AS FIELD_SOURCE"
            . " FROM RDB\$RELATION_FIELDS"
            . " WHERE RDB\$RELATION_NAME = " . $this->quote($table)
        );
        $fieldSources = $this->loadObjectList();
        $sourceCount = count($fieldSources);

        // Check if those field sources exist in RDB$FIELDS
        $fieldsTableCount = 0;
        if ($sourceCount > 0) {
            $fieldSource = trim($fieldSources[0]->field_source ?? '');
            $this->setQuery("SELECT COUNT(*) FROM RDB\$FIELDS WHERE RDB\$FIELD_NAME = " . $this->quote($fieldSource));
            $fieldsTableCount = (int) $this->loadResult();
        }

        // First, try the standard query with JOIN to RDB$FIELDS
        $this->setQuery("
            SELECT
                TRIM(rf.RDB\$FIELD_NAME) AS FIELD_NAME,
                f.RDB\$FIELD_TYPE AS FIELD_TYPE,
                f.RDB\$FIELD_SUB_TYPE AS FIELD_SUB_TYPE,
                f.RDB\$FIELD_LENGTH AS FIELD_LENGTH,
                f.RDB\$FIELD_PRECISION AS FIELD_PRECISION,
                f.RDB\$FIELD_SCALE AS FIELD_SCALE,
                f.RDB\$CHARACTER_LENGTH AS CHARLEN,
                rf.RDB\$NULL_FLAG AS NOT_NULL,
                rf.RDB\$DEFAULT_SOURCE AS DEFAULT_VALUE
            FROM RDB\$RELATION_FIELDS rf
            JOIN RDB\$FIELDS f ON rf.RDB\$FIELD_SOURCE = f.RDB\$FIELD_NAME
            WHERE rf.RDB\$RELATION_NAME = " . $this->quote($table) . "
            ORDER BY rf.RDB\$FIELD_POSITION
        ");

        $fields = $this->loadObjectList();

        // Firebird 3.0 MVCC workaround: If JOIN returns no results but fields exist in RDB$RELATION_FIELDS,
        // query RDB$RELATION_FIELDS and RDB$FIELDS separately to work around MVCC visibility issues
        if (empty($fields) && $fieldCount > 0) {
            // Get field information from RDB$RELATION_FIELDS (this is visible)
            $this->setQuery("
                SELECT
                    TRIM(RDB\$FIELD_NAME) AS FIELD_NAME,
                    TRIM(RDB\$FIELD_SOURCE) AS FIELD_SOURCE,
                    RDB\$NULL_FLAG AS NOT_NULL,
                    RDB\$DEFAULT_SOURCE AS DEFAULT_VALUE,
                    RDB\$FIELD_POSITION
                FROM RDB\$RELATION_FIELDS
                WHERE RDB\$RELATION_NAME = " . $this->quote($table) . "
                ORDER BY RDB\$FIELD_POSITION
            ");
            $relationFields = $this->loadObjectList();

            // For each field, try to get type info from RDB$FIELDS
            // If that fails, we'll use generic VARCHAR type as fallback
            foreach ($relationFields as $rf) {
                $fieldSource = trim($rf->field_source);

                $this->setQuery("
                    SELECT
                        RDB\$FIELD_TYPE AS field_type,
                        RDB\$FIELD_SUB_TYPE AS field_sub_type,
                        RDB\$FIELD_LENGTH AS field_length,
                        RDB\$FIELD_PRECISION AS field_precision,
                        RDB\$FIELD_SCALE AS field_scale,
                        RDB\$CHARACTER_LENGTH AS charlen
                    FROM RDB\$FIELDS
                    WHERE RDB\$FIELD_NAME = " . $this->quote($fieldSource));
                $fieldDef = $this->loadObject();

                // Combine the data (using lowercase property names for consistency)
                $fields[] = (object) [
                    'field_name'     => $rf->field_name,
                    'field_type'     => $fieldDef->field_type ?? 37,  // Default to VARCHAR
                    'field_sub_type' => $fieldDef->field_sub_type ?? 0,
                    'field_length'   => $fieldDef->field_length ?? 100,
                    'field_precision' => $fieldDef->field_precision ?? null,
                    'field_scale'    => $fieldDef->field_scale ?? null,
                    'charlen'        => $fieldDef->charlen ?? 100,
                    'not_null'       => $rf->not_null,
                    'default_value'  => $rf->default_value
                ];
            }
        }

        foreach ($fields as $field) {
            // PDO returns lowercase property names when ATTR_CASE = CASE_LOWER
            $name = trim($field->field_name ?? '');

            // Skip columns with empty names (shouldn't happen but defensive)
            if ($name === '') {
                continue;
            }

            $fullType = $this->buildFullColumnType(
                $field->field_type,
                $field->field_sub_type,
                $field->field_length,
                $field->field_precision,
                $field->field_scale,
                $field->charlen
            );

            $columns[] = (object) [
                'name'     => $name,
                'fullType' => $fullType,
                'nullable' => empty($field->not_null),
                'default'  => $field->default_value
            ];
        }

        return $columns;
    }

    /**
     * Build the full SQL column type from Firebird type metadata
     *
     * @param   int       $type       The Firebird field type code
     * @param   int|null  $subType    The field sub-type
     * @param   int|null  $length     The field length in bytes
     * @param   int|null  $precision  The field precision
     * @param   int|null  $scale      The field scale
     * @param   int|null  $charLen    The character length
     * @return  string
     */
    protected function buildFullColumnType(
        $type,
        $subType = null,
        $length = null,
        $precision = null,
        $scale = null,
        $charLen = null
    ) {
        // Firebird type codes
        switch ($type) {
            case 7:  // SMALLINT
                return 'SMALLINT';
            case 8:  // INTEGER
                return 'INTEGER';
            case 16: // BIGINT / INT64
                if ($subType == 1) {
                    return 'NUMERIC(' . ($precision ?: 18) . ', ' . abs($scale ?: 0) . ')';
                } elseif ($subType == 2) {
                    return 'DECIMAL(' . ($precision ?: 18) . ', ' . abs($scale ?: 0) . ')';
                }
                return 'BIGINT';
            case 10: // FLOAT
                return 'FLOAT';
            case 27: // DOUBLE PRECISION
                return 'DOUBLE PRECISION';
            case 12: // DATE
                return 'DATE';
            case 13: // TIME
                return 'TIME';
            case 35: // TIMESTAMP
                return 'TIMESTAMP';
            case 14: // CHAR
                $len = $charLen ?: ($length ?: 1);
                return 'CHAR(' . $len . ')';
            case 37: // VARCHAR
                $len = $charLen ?: ($length ? intval($length / 4) : 255);
                return 'VARCHAR(' . $len . ')';
            case 261: // BLOB
                if ($subType == 1) {
                    return 'BLOB SUB_TYPE 1';
                }
                return 'BLOB';
            case 23: // BOOLEAN (Firebird 3.0+)
                return 'BOOLEAN';
            default:
                return 'VARCHAR(255)';
        }
    }

    /**
     * Get primary key column names
     *
     * @param   string  $table  The table name
     * @return  array   Array of column names in the primary key
     */
    public function getPrimaryKeyColumns($table): array
    {
        $table = strtoupper($table);
        $columns = [];

        $this->setQuery("
            SELECT TRIM(i.RDB\$FIELD_NAME) AS COLUMN_NAME
            FROM RDB\$RELATION_CONSTRAINTS rc
            JOIN RDB\$INDEX_SEGMENTS i ON rc.RDB\$INDEX_NAME = i.RDB\$INDEX_NAME
            WHERE rc.RDB\$RELATION_NAME = " . $this->quote($table) . "
            AND rc.RDB\$CONSTRAINT_TYPE = 'PRIMARY KEY'
            ORDER BY i.RDB\$FIELD_POSITION
        ");

        $rows = $this->loadObjectList();
        foreach ($rows as $row) {
            // PDO returns lowercase property names when ATTR_CASE = CASE_LOWER
            // But the column name values from Firebird are still uppercase, so lowercase them
            $columns[] = strtolower(trim($row->column_name ?? ''));
        }

        return $columns;
    }

