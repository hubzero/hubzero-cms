    /**
     * Gets the auto-increment value for the given table
     *
     * Firebird uses generators (sequences) instead of auto-increment.
     * This attempts to find a generator associated with the table.
     *
     * @param   string    $table  The table
     * @return  int|bool
     */
    public function getAutoIncrement($table)
    {
        $this->commitBeforeMetadataQuery();

        $table = strtoupper($this->replacePrefix($table));

        // First check for IDENTITY columns (Firebird 3.0+)
        $this->setQuery("
            SELECT rf.RDB\$FIELD_NAME, rf.RDB\$GENERATOR_NAME
            FROM RDB\$RELATION_FIELDS rf
            WHERE rf.RDB\$RELATION_NAME = " . $this->quote($table) . "
            AND rf.RDB\$IDENTITY_TYPE IS NOT NULL
        ");

        $identityCol = $this->loadObject();
        if ($identityCol && isset($identityCol->{'rdb$generator_name'})) {
            $genName = trim($identityCol->{'rdb$generator_name'});
            $this->setQuery("SELECT GEN_ID(" . $genName . ", 0) FROM RDB\$DATABASE");
            $currentVal = $this->loadResult();
            return $currentVal !== null ? (int) $currentVal + 1 : 1;
        }

        // Fall back to common generator naming patterns for legacy tables
        $generatorNames = [
            'GEN_' . $table . '_ID',
            $table . '_ID_GEN',
            $table . '_SEQ',
            'SEQ_' . $table
        ];

        foreach ($generatorNames as $genName) {
            $this->setQuery("
                SELECT RDB\$GENERATOR_NAME FROM RDB\$GENERATORS
                WHERE RDB\$GENERATOR_NAME = " . $this->quote($genName) . "
            ");

            if ($this->loadResult()) {
                $this->setQuery("SELECT GEN_ID(" . $genName . ", 0) FROM RDB\$DATABASE");
                $currentVal = $this->loadResult();
                return $currentVal !== null ? (int) $currentVal + 1 : 1;
            }
        }

        return false;
    }

    /**
     * Sets the auto-increment starting value
     *
     * Firebird 3.0+ uses IDENTITY columns. This resets the identity sequence.
     * Also supports legacy generators for backward compatibility.
     *
     * @param   string  $table  The table name
     * @param   int     $value  The starting value
     * @return  bool
     */
    public function setAutoIncrement($table, $value): bool
    {
        $this->commitBeforeMetadataQuery();

        $table = strtoupper($this->replacePrefix($table));
        $value = (int) $value;

        // MySQL treats AUTO_INCREMENT = 0 as 1 (next insert gets ID=1)
        // Match this behavior for consistency across drivers
        if ($value <= 0) {
            $value = 1;
        }

        // First, try to find an IDENTITY column (Firebird 3.0+)
        // IDENTITY columns have their identity info in RDB$RELATION_FIELDS
        $this->setQuery("
            SELECT TRIM(RF.RDB\$FIELD_NAME) AS field_name
            FROM RDB\$RELATION_FIELDS RF
            JOIN RDB\$FIELDS F ON RF.RDB\$FIELD_SOURCE = F.RDB\$FIELD_NAME
            WHERE RF.RDB\$RELATION_NAME = " . $this->quote($table) . "
            AND RF.RDB\$IDENTITY_TYPE IS NOT NULL
        ");

        $result = $this->loadResult();
        if ($result) {
            // Found an IDENTITY column - reset with ALTER TABLE ... RESTART
            // Note: RESTART WITH n sets the current value, next INSERT gets n+1
            // So to have next INSERT get value V, we need RESTART WITH (V-1)
            $columnName = strtoupper(trim($result));
            $restartValue = $value - 1;  // Subtract 1 because next value = restart + 1
            $this->setQuery("ALTER TABLE " . $this->quoteName($table) .
                           " ALTER COLUMN " . $this->quoteName($columnName) .
                           " RESTART WITH " . $restartValue);
            $this->execute();

            // Commit to ensure the change takes effect
            if ($this->connection && $this->connection->inTransaction()) {
                if ($this->transactionDepth == 0) {
                    $this->connection->commit();
                }
            } elseif ($this->connection) {
                $this->connection->beginTransaction();
                $this->connection->commit();
            }

            return true;
        }

        // Fallback: Try legacy generator approach
        $genValue = $value - 1;  // Generators are 0-based, next value = current + 1
        $generatorNames = [
            'GEN_' . $table . '_ID',
            $table . '_ID_GEN',
            $table . '_SEQ',
            'SEQ_' . $table
        ];

        foreach ($generatorNames as $genName) {
            $this->setQuery("
                SELECT RDB\$GENERATOR_NAME FROM RDB\$GENERATORS
                WHERE RDB\$GENERATOR_NAME = " . $this->quote($genName) . "
            ");

            if ($this->loadResult()) {
                $this->setQuery("SET GENERATOR " . $this->quoteName($genName) . " TO " . $genValue);
                $this->execute();

                // Commit to ensure it takes effect
                if ($this->connection && $this->connection->inTransaction()) {
                    if ($this->transactionDepth == 0) {
                        $this->connection->commit();
                    }
                } elseif ($this->connection) {
                    $this->connection->beginTransaction();
                    $this->connection->commit();
                }

                return true;
            }
        }

        return false;
    }

