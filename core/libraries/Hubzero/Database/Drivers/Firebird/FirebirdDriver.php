    /**
     * Map a MySQL-style column type to Firebird's type
     *
     * @param   string  $type  The MySQL column type
     * @return  string  The Firebird column type
     */
    public function mapColumnType(string $type): string
    {
        $upper = strtoupper($type);

        // Remove UNSIGNED (Firebird doesn't support it)
        $upper = preg_replace('/\s+UNSIGNED$/i', '', $upper);

        // TINYINT -> SMALLINT
        if (preg_match('/^TINYINT(\s*\(\d+\))?$/i', $upper)) {
            return 'SMALLINT';
        }

        // MEDIUMINT -> INTEGER
        if (preg_match('/^MEDIUMINT(\s*\(\d+\))?$/i', $upper)) {
            return 'INTEGER';
        }

        // INT(n) -> INTEGER
        if (preg_match('/^INT(EGER)?(\s*\(\d+\))?$/i', $upper)) {
            return 'INTEGER';
        }

        // BIGINT(n) -> BIGINT
        if (preg_match('/^BIGINT(\s*\(\d+\))?$/i', $upper)) {
            return 'BIGINT';
        }

        // DOUBLE/FLOAT -> DOUBLE PRECISION
        if ($upper === 'DOUBLE' || $upper === 'FLOAT' || preg_match('/^(DOUBLE|FLOAT)\s*\([^)]+\)$/i', $upper)) {
            return 'DOUBLE PRECISION';
        }

        // DECIMAL/NUMERIC -> DECIMAL
        if (preg_match('/^(DECIMAL|NUMERIC)\s*\(([^)]+)\)$/i', $upper, $matches)) {
            return "DECIMAL({$matches[2]})";
        }

        // DATETIME/TIMESTAMP -> TIMESTAMP
        if ($upper === 'DATETIME' || $upper === 'TIMESTAMP') {
            return 'TIMESTAMP';
        }

        // TEXT types -> BLOB SUB_TYPE 1
        if ($upper === 'TINYTEXT') {
            return 'BLOB SUB_TYPE 1';
        }
        if ($upper === 'TEXT') {
            return 'BLOB SUB_TYPE 1';
        }
        if ($upper === 'MEDIUMTEXT' || $upper === 'LONGTEXT') {
            return 'BLOB SUB_TYPE 1';
        }

        // BLOB types -> BLOB
        if (preg_match('/^(TINY|MEDIUM|LONG)?BLOB$/i', $upper)) {
            return 'BLOB';
        }

        // BOOLEAN -> BOOLEAN (Firebird 3.0+ has native boolean)
        if ($upper === 'BOOLEAN' || $upper === 'BOOL' || $upper === 'TINYINT(1)') {
            return 'BOOLEAN';
        }

        // ENUM -> VARCHAR(255)
        if (preg_match('/^ENUM\s*\(/i', $upper)) {
            return 'VARCHAR(255)';
        }

        // SET -> VARCHAR(255) (Firebird has no SET type)
        if (preg_match('/^SET\s*\(/i', $upper)) {
            return 'VARCHAR(255)';
        }

        // YEAR -> SMALLINT (Firebird has no YEAR type)
        if ($upper === 'YEAR' || preg_match('/^YEAR\s*\(\d+\)$/i', $upper)) {
            return 'SMALLINT';
        }

        return $type;
    }

