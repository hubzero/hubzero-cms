    /**
     * Normalize abstract column types to Firebird-specific types
     *
     * Delegates to the parent for abstract types found in $this->typeMap,
     * which applies modifiers via applyColumnModifiers(). Only handles
     * SET/ENUM fallthrough locally.
     *
     * @param   string  $type       The abstract or concrete type
     * @param   array   $modifiers  Column modifiers (length, precision, etc.)
     * @return  string  The Firebird-specific type definition
     */
    public function normalizeColumnType(
        string $type,
        array $modifiers = []
    ): string {
        if ($this->getSchemaGrammar()->getTypeMapping($type) !== null) {
            return parent::normalizeColumnType($type, $modifiers);
        }

        // Handle MySQL SET() type -> VARCHAR(255)
        if (preg_match('/^SET\s*\(/i', $type)) {
            return 'VARCHAR(255)';
        }

        // Handle MySQL ENUM() type -> VARCHAR(255)
        if (preg_match('/^ENUM\s*\(/i', $type)) {
            return 'VARCHAR(255)';
        }

        // Already a concrete Firebird type
        return $type;
    }

    /**
     * Apply length/precision modifiers to a mapped column type
     *
     * Extends the base to support integer display widths (like MySQL).
     * Firebird allows display width on integer types (e.g., INTEGER(11)).
     *
     * @param   string  $abstractType  The original abstract type name
     * @param   string  $nativeType    The mapped Firebird type
     * @param   array   $modifiers     Column modifiers
     * @return  string  The type with modifiers applied
     */
    protected function applyColumnModifiers(
        string $abstractType,
        string $nativeType,
        array $modifiers
    ): string {
        // Firebird supports display width on integer types
        $integerTypes = [
            'tinyInteger', 'smallInteger',
            'mediumInteger', 'integer', 'bigInteger',
        ];
        if (
            isset($modifiers['length'])
            && in_array($abstractType, $integerTypes)
        ) {
            return "{$nativeType}({$modifiers['length']})";
        }

        return parent::applyColumnModifiers(
            $abstractType,
            $nativeType,
            $modifiers
        );
    }

    /**
     * Build column definition for ALTER TABLE ADD COLUMN
     *
     * Firebird-specific rules:
     * - DEFAULT must come before NOT NULL
     * - Never output standalone NULL keyword (only NOT NULL or omit)
     * - Use GENERATED BY DEFAULT AS IDENTITY for auto-increment
     *
     * @param   string  $name        Column name
     * @param   array   $definition  Column definition array with 'type' and 'modifiers'
     * @return  string  Column definition SQL
     */
    public function buildAlterColumnDefinition(string $name, array $definition): string
    {
        $type = $definition['type'];
        $modifiers = $definition['modifiers'] ?? [];

        // Normalize abstract types (like 'string') to Firebird types (like 'VARCHAR(255)')
        $type = $this->normalizeColumnType($type, $modifiers);

        // Handle AUTO_INCREMENT -> GENERATED BY DEFAULT AS IDENTITY
        $hasAutoIncrement = !empty($modifiers['autoIncrement'])
            || stripos($type, 'AUTO_INCREMENT') !== false
            || stripos($type, 'IDENTITY') !== false;

        // Clean up type string
        $type = preg_replace('/\s*AUTO_INCREMENT\s*/i', ' ', $type);
        $type = preg_replace('/\s*GENERATED\s+BY\s+DEFAULT\s+AS\s+IDENTITY\s*/i', ' ', $type);
        $type = trim($type);

        // Start with column name and type
        $parts = [$this->quoteName($name), $type];

        // AUTO_INCREMENT becomes GENERATED BY DEFAULT AS IDENTITY
        if ($hasAutoIncrement) {
            $parts[] = 'GENERATED BY DEFAULT AS IDENTITY';
        }

        // Translate zero-date default to NULL
        if (
            array_key_exists('default', $modifiers)
            && self::isZeroDate($modifiers['default'])
        ) {
            $modifiers['nullable'] = true;
            $modifiers['default'] = null;
        }

        // DEFAULT value (must come before NOT NULL in Firebird)
        if (array_key_exists('default', $modifiers)) {
            $default = $modifiers['default'];
            if ($default === null) {
                $parts[] = 'DEFAULT NULL';
            } elseif (is_bool($default)) {
                $parts[] = 'DEFAULT ' . ($default ? 'TRUE' : 'FALSE');
            } elseif (is_numeric($default)) {
                $parts[] = 'DEFAULT ' . $default;
            } elseif ($default === 'CURRENT_TIMESTAMP') {
                $parts[] = 'DEFAULT CURRENT_TIMESTAMP';
            } else {
                $parts[] = "DEFAULT '" . str_replace("'", "''", $default) . "'";
            }
        }

        // NOT NULL (only if explicitly not nullable, never output standalone NULL)
        if (isset($modifiers['nullable']) && !$modifiers['nullable'] && !$hasAutoIncrement) {
            $parts[] = 'NOT NULL';
        }

        return implode(' ', $parts);
    }

    /**
     * Rebuild a Firebird table to apply column positioning
     *
     * Firebird doesn't support AFTER/BEFORE in ALTER TABLE ADD COLUMN.
     * This method rebuilds the table with columns in the correct order.
     *
     * @param   string  $table    Table name (already prefixed)
     * @param   \Hubzero\Database\Schema\AlterTableBuilder  $builder  The table builder
     * @return  array  Array of SQL statements
     */
    protected function buildFirebirdTableRebuild(
        string $table,
        \Hubzero\Database\Schema\AlterTableBuilder $builder
    ): array {
        $statements = [];
        $table = strtoupper($table);
        $tempTable = $table . '_RB_' . time();

        // Get current table structure from Firebird system tables
        $this->setQuery("
            SELECT TRIM(rf.RDB\$FIELD_NAME) as field_name,
                   TRIM(f.RDB\$FIELD_TYPE) as field_type,
                   f.RDB\$FIELD_LENGTH as field_length,
                   rf.RDB\$NULL_FLAG as null_flag,
                   rf.RDB\$DEFAULT_SOURCE as default_source,
                   f.RDB\$FIELD_SUB_TYPE as field_sub_type,
                   f.RDB\$CHARACTER_LENGTH as char_length,
                   rf.RDB\$FIELD_POSITION as field_position,
                   rf.RDB\$IDENTITY_TYPE as identity_type
            FROM RDB\$RELATION_FIELDS rf
            JOIN RDB\$FIELDS f ON rf.RDB\$FIELD_SOURCE = f.RDB\$FIELD_NAME
            WHERE rf.RDB\$RELATION_NAME = " . $this->quote($table) . "
            ORDER BY rf.RDB\$FIELD_POSITION
        ");
        $currentColumns = $this->loadObjectList();

        if (empty($currentColumns)) {
            return $statements;
        }

        // Build ordered column list
        $orderedColumns = [];
        foreach ($currentColumns as $col) {
            $colName = trim($col->field_name);
            $orderedColumns[$colName] = $col;
        }

        // Process added columns with positioning
        foreach ($builder->getAddColumns() as $name => $definition) {
            $modifiers = $definition['modifiers'] ?? [];

            if (isset($modifiers['after'])) {
                // Insert after specified column
                $afterColumn = $modifiers['after'];
                $newOrdered = [];
                foreach ($orderedColumns as $existingName => $existingCol) {
                    $newOrdered[$existingName] = $existingCol;
                    if ($existingName === $afterColumn) {
                        $newOrdered[$name] = $definition;
                    }
                }
                $orderedColumns = $newOrdered;
            } elseif (isset($modifiers['before'])) {
                // Insert before specified column
                $beforeColumn = $modifiers['before'];
                $newOrdered = [];
                foreach ($orderedColumns as $existingName => $existingCol) {
                    if ($existingName === $beforeColumn) {
                        $newOrdered[$name] = $definition;
                    }
                    $newOrdered[$existingName] = $existingCol;
                }
                $orderedColumns = $newOrdered;
            } else {
                // Add at end
                $orderedColumns[$name] = $definition;
            }
        }

        // Build new column definitions
        $newColumnDefs = [];
        $selectColumns = [];
        $targetColumns = [];

        foreach ($orderedColumns as $colName => $colInfo) {
            if (is_array($colInfo)) {
                // New column from builder
                $colDef = $this->buildAlterColumnDefinition($colName, $colInfo);
                $newColumnDefs[] = $colDef;
                // New columns won't be in SELECT (no source data)
            } else {
                // Existing column from database
                $colDef = $this->quoteName($colName) . ' ';

                // Map Firebird type codes to type names
                $typeMap = [
                    7 => 'SMALLINT', 8 => 'INTEGER', 10 => 'FLOAT', 12 => 'DATE',
                    13 => 'TIME', 14 => 'CHAR', 16 => 'BIGINT', 27 => 'DOUBLE PRECISION',
                    35 => 'TIMESTAMP', 37 => 'VARCHAR', 261 => 'BLOB'
                ];

                $fieldType = $typeMap[$colInfo->field_type] ?? 'VARCHAR';

                if ($fieldType === 'VARCHAR' || $fieldType === 'CHAR') {
                    $colDef .= $fieldType . '(' . ($colInfo->char_length ?? $colInfo->field_length) . ')';
                } elseif ($fieldType === 'BLOB' && $colInfo->field_sub_type == 1) {
                    $colDef .= 'BLOB SUB_TYPE 1';
                } else {
                    $colDef .= $fieldType;
                }

                // Handle IDENTITY (auto-increment) - must come before NOT NULL
                if ($colInfo->identity_type !== null) {
                    if ($colInfo->identity_type == 0) {
                        $colDef .= ' GENERATED ALWAYS AS IDENTITY';
                    } elseif ($colInfo->identity_type == 1) {
                        $colDef .= ' GENERATED BY DEFAULT AS IDENTITY';
                    }
                }

                // Handle NOT NULL
                if ($colInfo->null_flag) {
                    $colDef .= ' NOT NULL';
                }

                // Handle DEFAULT (skip if it's identity-related)
                if ($colInfo->default_source && $colInfo->identity_type === null) {
                    $colDef .= ' ' . trim($colInfo->default_source);
                }

                $newColumnDefs[] = $colDef;

                // For identity columns, don't include in INSERT...SELECT
                // Firebird will generate values automatically
                if ($colInfo->identity_type === null) {
                    $selectColumns[] = $this->quoteName($colName);
                    $targetColumns[] = $this->quoteName($colName);
                }
            }
        }

        // Execute rebuild
        $statements[] = "CREATE TABLE " . $this->quoteName($tempTable) . " (" . implode(', ', $newColumnDefs) . ")";

        if (!empty($selectColumns)) {
            $statements[] = "INSERT INTO " . $this->quoteName($tempTable)
                . " (" . implode(', ', $targetColumns) . ")"
                . " SELECT " . implode(', ', $selectColumns)
                . " FROM " . $this->quoteName($table);
        }

        $statements[] = "DROP TABLE " . $this->quoteName($table);
        $statements[] = "ALTER TABLE " . $this->quoteName($tempTable) . " TO " . $this->quoteName($table);

        return $statements;
    }

    /**
     * Helper to find PK constraint name
     *
     * @param   string  $table  The table name
     * @return  string|null
     */
    public function getPrimaryKeyConstraintName($table)
    {
        $table = strtoupper($this->replacePrefix($table));
        $this->setQuery("
            SELECT TRIM(rc.RDB\$CONSTRAINT_NAME)
            FROM RDB\$RELATION_CONSTRAINTS rc
            WHERE rc.RDB\$RELATION_NAME = " . $this->quote($table) . "
            AND rc.RDB\$CONSTRAINT_TYPE = 'PRIMARY KEY'
        ");
        return $this->loadResult();
    }

    /**
     * Get column type information from Firebird system tables
     *
     * Returns an object with field_type, field_length, and character_length
     * properties for the specified column. Used by Grammar for ALTER TABLE
     * operations that need current column type.
     *
     * @param   string  $table   Table name
     * @param   string  $column  Column name
     * @return  object|null  Column type info or null if column doesn't exist
     */
    public function getColumnTypeInfo(string $table, string $column): ?object
    {
        $table = strtoupper($this->replacePrefix($table));
        $column = strtoupper($column);

        $this->setQuery("
            SELECT f.RDB\$FIELD_TYPE, f.RDB\$FIELD_LENGTH, f.RDB\$CHARACTER_LENGTH
            FROM RDB\$RELATION_FIELDS rf
            JOIN RDB\$FIELDS f ON rf.RDB\$FIELD_SOURCE = f.RDB\$FIELD_NAME
            WHERE rf.RDB\$FIELD_NAME = " . $this->quote($column) . "
            AND rf.RDB\$RELATION_NAME = " . $this->quote($table));

        return $this->loadObject();
    }

    /**
     * Get full table structure from Firebird system tables
     *
     * Returns an array of column information objects with field_name,
     * field_type, field_length, null_flag, default_source, etc.
     * Used by Grammar for table rebuild operations.
     *
     * @param   string  $table  Table name
     * @return  array   Array of column info objects, ordered by field position
     */
    public function getTableStructureInfo(string $table): array
    {
        $table = strtoupper($this->replacePrefix($table));

        $this->setQuery("
            SELECT TRIM(rf.RDB\$FIELD_NAME) as field_name,
                   TRIM(f.RDB\$FIELD_TYPE) as field_type,
                   f.RDB\$FIELD_LENGTH as field_length,
                   rf.RDB\$NULL_FLAG as null_flag,
                   rf.RDB\$DEFAULT_SOURCE as default_source,
                   f.RDB\$FIELD_SUB_TYPE as field_sub_type,
                   f.RDB\$CHARACTER_LENGTH as char_length,
                   rf.RDB\$FIELD_POSITION as field_position,
                   rf.RDB\$IDENTITY_TYPE as identity_type
            FROM RDB\$RELATION_FIELDS rf
            JOIN RDB\$FIELDS f ON rf.RDB\$FIELD_SOURCE = f.RDB\$FIELD_NAME
            WHERE rf.RDB\$RELATION_NAME = " . $this->quote($table) . "
            ORDER BY rf.RDB\$FIELD_POSITION
        ");

        return $this->loadObjectList() ?: [];
    }

