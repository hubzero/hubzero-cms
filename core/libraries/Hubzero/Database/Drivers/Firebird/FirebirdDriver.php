    /**
     * Drop the primary key from a table
     *
     * @param   string  $table  Table name
     * @return  bool
     */
    public function dropPrimaryKey(string $table): bool
    {
        $table = strtoupper($this->replacePrefix($table));

        // Find the primary key constraint name
        $this->setQuery("
            SELECT TRIM(rc.RDB\$CONSTRAINT_NAME) AS constraint_name
            FROM RDB\$RELATION_CONSTRAINTS rc
            WHERE rc.RDB\$RELATION_NAME = " . $this->quote($table) . "
            AND rc.RDB\$CONSTRAINT_TYPE = 'PRIMARY KEY'
        ");

        $constraintName = $this->loadResult();

        if (!$constraintName) {
            return true; // No primary key exists
        }

        $query = 'ALTER TABLE ' . $this->quoteName($table) .
                 ' DROP CONSTRAINT ' . $this->quoteName(trim($constraintName ?? ''));

        $this->setQuery($query);
        return (bool) $this->execute();
    }

    /**
     * Add a primary key to a table
     *
     * @param   string        $table    Table name
     * @param   string|array  $columns  Column name(s)
     * @return  bool
     */
    public function addPrimaryKey(string $table, $columns): bool
    {
        $table = strtoupper($this->replacePrefix($table));

        if (is_string($columns)) {
            $columns = [$columns];
        }

        // Firebird requires primary key columns to be NOT NULL
        // Make sure all columns are NOT NULL first
        foreach ($columns as $col) {
            $colUpper = strtoupper($col);
            $quotedCol = $this->quoteName($colUpper);

            // Check if column is nullable
            $this->setQuery("
                SELECT rf.RDB\$NULL_FLAG
                FROM RDB\$RELATION_FIELDS rf
                WHERE rf.RDB\$RELATION_NAME = " . $this->quote($table) . "
                AND rf.RDB\$FIELD_NAME = " . $this->quote($colUpper) . "
            ");

            $nullFlag = $this->loadResult();

            // If NULL_FLAG is null or 0, column is nullable - make it NOT NULL
            if (!$nullFlag) {
                $this->setQuery('ALTER TABLE ' . $this->quoteName($table) .
                               ' ALTER COLUMN ' . $quotedCol . ' SET NOT NULL');
                $this->execute();
            }
        }

        $columnList = implode(', ', array_map(function ($col) {
            return $this->quoteName(strtoupper($col));
        }, $columns));

        $query = 'ALTER TABLE ' . $this->quoteName($table) .
                 ' ADD PRIMARY KEY (' . $columnList . ')';

        $this->setQuery($query);
        return (bool) $this->execute();
    }

    /**
     * Add an auto-increment primary key column
     *
     * @param   string  $table      Table name
     * @param   string  $column     Column name
     * @param   bool    $first      Add as first column (ignored in Firebird)
     * @param   bool    $useBigInt  Use BIGINT
     * @return  bool
     */
    public function addAutoIncrementPrimaryKey(
        string $table,
        string $column = 'id',
        bool $first = false,
        bool $useBigInt = true
    ): bool {
        $table = strtoupper($this->replacePrefix($table));
        $column = strtoupper($column);

        // Check if table exists
        if (!$this->tableExists($table)) {
            return false;
        }

        // Check if column already exists (idempotent)
        if ($this->tableHasField($table, $column)) {
            return true;
        }

        $type = $useBigInt ? 'BIGINT' : 'INTEGER';

        // Check if table has existing data
        $this->setQuery('SELECT COUNT(*) FROM ' . $this->quoteName($table));
        $count = (int) $this->loadResult();

        if ($count > 0) {
            // Table has data - simpler approach: add nullable column, populate with ROW_NUMBER, make NOT NULL
            // Step 1: Add column as nullable
            $definition = $type;
            if (!$this->addColumn($table, $column, $definition)) {
                return false;
            }

            // Step 2: Populate using EXECUTE BLOCK to assign sequential IDs
            // Use Firebird's RDB$DB_KEY pseudo-column as unique row identifier
            $executeBlock = 'EXECUTE BLOCK AS
DECLARE VARIABLE row_id CHAR(8) CHARACTER SET OCTETS;
DECLARE VARIABLE counter INTEGER;
BEGIN
    counter = 1;
    FOR SELECT RDB$DB_KEY FROM ' . $this->quoteName($table) . ' INTO :row_id DO
    BEGIN
        UPDATE ' . $this->quoteName($table) . '
        SET ' . $this->quoteName($column) . ' = :counter
        WHERE RDB$DB_KEY = :row_id;
        counter = counter + 1;
    END
END';

            $this->setQuery($executeBlock);
            if (!$this->execute()) {
                return false;
            }

            // Get the next ID value for the sequence
            $this->setQuery('SELECT MAX(' . $this->quoteName($column) . ') FROM ' . $this->quoteName($table));
            $maxId = (int) $this->loadResult();
            $id = $maxId + 1;

            // Step 3: Make column NOT NULL
            $this->setQuery('ALTER TABLE ' . $this->quoteName($table) .
                           ' ALTER COLUMN ' . $this->quoteName($column) . ' SET NOT NULL');
            if (!$this->execute()) {
                return false;
            }

            // Step 4: Add primary key constraint
            $this->setQuery('ALTER TABLE ' . $this->quoteName($table) .
                           ' ADD PRIMARY KEY (' . $this->quoteName($column) . ')');
            if (!$this->execute()) {
                return false;
            }

            // Step 5: Create a generator/sequence for future inserts
            // We can't convert to IDENTITY after the fact, so create a sequence
            $generatorName = 'GEN_' . $table . '_' . $column;
            $this->setQuery('CREATE SEQUENCE ' . $this->quoteName($generatorName));
            try {
                $this->execute();
            } catch (\Exception $e) {
                // Sequence might already exist
            }

            // Set sequence to continue from current max
            $this->setQuery('ALTER SEQUENCE ' . $this->quoteName($generatorName) . ' RESTART WITH ' . $id);
            $this->execute();

            return true;
        } else {
            // Empty table - can add IDENTITY column directly
            $definition = $type . ' GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY';
            return $this->addColumn($table, $column, $definition);
        }
    }

    /**
     * Populate a column with sequential integer values
     *
     * @param   string       $table    Table name
     * @param   string       $column   Column name
     * @param   string|null  $orderBy  Optional column to order by
     * @return  bool
     */
    public function populateSequentialValues(string $table, string $column, ?string $orderBy = null): bool
    {
        $table = strtoupper($this->replacePrefix($table));
        $column = strtoupper($column);

        $orderClause = '';
        if ($orderBy) {
            $orderClause = ' ORDER BY ' . $this->quoteName(strtoupper($orderBy));
        }

        // Firebird doesn't have row_number by default in older versions
        // Use a cursor-based approach or execute multiple updates
        $this->setQuery('SELECT COUNT(*) FROM ' . $this->quoteName($table));
        $count = (int) $this->loadResult();

        if ($count === 0) {
            return true;
        }

        // Get all rows (need to determine ordering)
        $pk = $this->getPrimaryKey($table);
        if (!$pk || strtoupper($pk) === $column) {
            // No other primary key to use for ordering
            return false;
        }

        $this->setQuery('SELECT ' . $this->quoteName($pk) . ' FROM ' . $this->quoteName($table) . $orderClause);
        $rows = $this->loadColumn();

        $value = 1;
        foreach ($rows as $pkValue) {
            $this->setQuery('UPDATE ' . $this->quoteName($table) .
                           ' SET ' . $this->quoteName($column) . ' = ' . $value .
                           ' WHERE ' . $this->quoteName($pk) . ' = ' . $this->quote($pkValue));
            $this->execute();
            $value++;
        }

        return true;
    }

