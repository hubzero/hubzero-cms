        // Parse definition to separate type from constraints
        // Firebird requires separate statements for TYPE and NOT NULL
        $definition = trim($definition);
        $notNull = null;
        $defaultValue = null;

        // Extract NOT NULL or NULL constraint
        if (preg_match('/\s+(NOT\s+NULL|NULL)\s*$/i', $definition, $matches)) {
            $notNull = strtoupper(trim($matches[1]));
            $definition = trim(preg_replace('/\s+(NOT\s+NULL|NULL)\s*$/i', '', $definition));
        }

        // Extract DEFAULT value
        if (preg_match('/\s+DEFAULT\s+(.+?)(?:\s+(NOT\s+NULL|NULL))?$/i', $definition, $matches)) {
            $defaultValue = trim($matches[1]);
            $definition = trim(preg_replace('/\s+DEFAULT\s+.+$/i', '', $definition));
        }

        // Execute ALTER COLUMN TYPE
        $query = 'ALTER TABLE ' . $this->quoteName($table) .
                 ' ALTER COLUMN ' . $this->quoteName($column) .
                 ' TYPE ' . $definition;

        $this->setQuery($query);
        if (!$this->execute()) {
            return false;
        }

        // Handle NOT NULL constraint separately
        if ($notNull === 'NOT NULL') {
            $query = 'ALTER TABLE ' . $this->quoteName($table) .
                     ' ALTER COLUMN ' . $this->quoteName($column) .
                     ' SET NOT NULL';
            $this->setQuery($query);
            if (!$this->execute()) {
                return false;
            }
        } elseif ($notNull === 'NULL') {
            $query = 'ALTER TABLE ' . $this->quoteName($table) .
                     ' ALTER COLUMN ' . $this->quoteName($column) .
                     ' DROP NOT NULL';
            $this->setQuery($query);
            if (!$this->execute()) {
                return false;
            }
        }

        // Handle DEFAULT value separately
        if ($defaultValue !== null) {
            $query = 'ALTER TABLE ' . $this->quoteName($table) .
                     ' ALTER COLUMN ' . $this->quoteName($column) .
                     ' SET DEFAULT ' . $defaultValue;
            $this->setQuery($query);
            if (!$this->execute()) {
                return false;
            }
        }

        return true;
    }

