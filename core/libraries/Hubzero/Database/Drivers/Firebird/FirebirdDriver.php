    // =========================================================================
    // Fetch Method Overrides - Normalize Column Names to Lowercase
    // =========================================================================
    // Firebird returns column names in UPPERCASE by default. The ORM expects
    // lowercase column names (e.g., 'id' not 'ID'). These overrides normalize
    // all column names to lowercase to ensure ORM compatibility.
    // =========================================================================

    /**
     * Fetches a row from the result set as an object
     *
     * Normalizes column names to lowercase for ORM compatibility.
     *
     * @param   string       $class  The class name to use for the returned row object
     * @return  object|null
     */
    protected function fetchObject($class = 'stdClass')
    {
        // Check if we have a cached RETURNING row
        if ($this->cachedReturningRow !== null) {
            $row = $this->cachedReturningRow;
            $this->cachedReturningRow = null; // Clear cache after using
        } else {
            $row = $this->statement->fetch(\PDO::FETCH_ASSOC);

            if ($row === false) {
                return null;
            }

            // Normalize keys to lowercase
            $row = array_change_key_case($row, CASE_LOWER);
        }

        // Convert to object of the requested class
        if ($class === 'stdClass') {
            return (object) $row;
        }

        // For custom classes, create instance and set properties
        $obj = new $class();
        foreach ($row as $key => $value) {
            $obj->$key = $value;
        }

        return $obj;
    }

    /**
     * Fetches a row from the result set as an indexed array
     *
     * Overrides parent to support cached RETURNING rows.
     *
     * @return  array|null
     */
    protected function fetchArray()
    {
        // Check if we have a cached RETURNING row
        if ($this->cachedReturningRow !== null) {
            $row = array_values($this->cachedReturningRow);
            $this->cachedReturningRow = null; // Clear cache after using
            return $row;
        }

        // Otherwise, use parent's implementation
        return parent::fetchArray();
    }

    /**
     * Fetches a row from the result set as an associative array
     *
     * Normalizes column names to lowercase for ORM compatibility.
     * Supports cached RETURNING rows.
     *
     * @return  array|false
     */
    protected function fetchAssoc()
    {
        // Check if we have a cached RETURNING row
        if ($this->cachedReturningRow !== null) {
            $row = $this->cachedReturningRow;
            $this->cachedReturningRow = null; // Clear cache after using
            return $row;
        }

        $row = $this->statement->fetch(\PDO::FETCH_ASSOC);

        if ($row === false) {
            return false;
        }

        // Normalize keys to lowercase
        return array_change_key_case($row, CASE_LOWER);
    }

    // =========================================================================
    // Transaction Management Overrides
    // =========================================================================

    /**
     * Prepares a query for binding
     *
     * Overrides to auto-start a transaction if needed, since Firebird
     * requires explicit transactions when ATTR_AUTOCOMMIT is off.
     *
     * @param   string  $statement  The statement to prepare
     * @return  $this
     */
    public function prepare($statement)
    {
        // Firebird with ATTR_AUTOCOMMIT=false requires explicit transactions.
        // Auto-start one if not already in a transaction and not user-managed.
        if ($this->connection && !$this->connection->inTransaction() && $this->transactionDepth == 0) {
            $this->connection->beginTransaction();
        }

        return parent::prepare($statement);
    }

    /**
     * Executes a raw SQL statement directly without prepared statements
     *
     * Firebird requires ATTR_AUTOCOMMIT=false for proper transaction support.
     * To emulate autocommit behavior matching other drivers, we:
     * - Auto-start a transaction if not in an explicit transaction
     * - Auto-commit after each statement when transactionDepth == 0
     * - Keep transaction open when in explicit transaction (transactionDepth > 0)
     *
     * @param   string  $statement  The SQL statement to execute
     * @return  int     The number of affected rows
     */
    public function exec($statement)
    {
        // Start implicit transaction if not in an explicit one
        if ($this->connection && !$this->connection->inTransaction() && $this->transactionDepth == 0) {
            $this->connection->beginTransaction();
        }

        try {
            $result = parent::exec($statement);

            // Emulate autocommit: commit implicit transactions immediately
            // This matches behavior of other drivers with ATTR_AUTOCOMMIT=true
            if ($this->transactionDepth == 0 && $this->connection && $this->connection->inTransaction()) {
                $this->connection->commit();
            }

            return $result;
        } catch (\Exception $e) {
            // Rollback implicit transaction on error
            if ($this->transactionDepth == 0 && $this->connection && $this->connection->inTransaction()) {
                $this->connection->rollBack();
            }
            throw $e;
        }
    }

    /**
     * Execute a query
     *
     * CRITICAL: Handles RETURNING clause caching for Firebird
     *
     * When a query contains RETURNING (INSERT/UPDATE ... RETURNING columns),
     * the result row must be fetched immediately after execution. However,
     * this creates a problem: if we fetch it here, it won't be available
     * for loadResult()/loadObject() calls later.
     *
     * Solution: We cache the RETURNING row in $cachedReturningRow, which
     * is then returned by the first fetch operation (fetchObject/fetchArray/
     * fetchAssoc) instead of fetching from the statement again.
     *
     * This allows both patterns to work:
     *   $db->setQuery("INSERT ... RETURNING ID");
     *   $db->execute();
     *   $id = $db->insertid();  // Works - uses cached row
     *
     *   $db->setQuery("INSERT ... RETURNING ID");
     *   $id = $db->loadResult();  // Also works - uses cached row
     *
     * The cache is cleared after first use to prevent stale data.
     *
     * Emulates autocommit behavior matching other drivers by committing
     * implicit transactions after non-SELECT statements.
     *
     * @return  mixed
     */
    public function execute()
    {
        $sql = $this->statement->queryString ?? '';

        // Reset last insert ID and cached row
        $this->lastInsertId = null;
        $this->cachedReturningRow = null;

        // Capture table name from INSERT statements (for fallback)
        if (preg_match('/^\s*INSERT\s+INTO\s+"?([^"\s(]+)"?/i', $sql, $matches)) {
            $this->lastInsertTable = strtoupper(trim($matches[1]));
        }

        // Check if this is a query with RETURNING
        $hasReturning = preg_match('/\bRETURNING\s+/i', $sql);

        try {
            // Execute the statement
            $result = parent::execute();

            // If query with RETURNING succeeded, fetch and cache the returned row
            if ($result && $hasReturning) {
                $row = $this->statement->fetch(\PDO::FETCH_ASSOC);
                if ($row) {
                    // Normalize keys to lowercase and cache the row
                    $row = array_change_key_case($row, CASE_LOWER);
                    $this->cachedReturningRow = $row;

                    // Extract ID for lastInsertId if available
                    $this->lastInsertId = isset($row['id']) ? (int) $row['id'] : null;
                }
            }

            // Emulate autocommit: commit implicit transactions after write operations
            // For SELECTs (columnCount > 0), commit happens in freeResult() after fetching
            if ($this->transactionDepth == 0 && $this->connection && $this->connection->inTransaction()) {
                // Always commit DDL operations (CREATE, ALTER, DROP) to prevent deadlocks
                $isDDL = preg_match('/^\s*(CREATE|ALTER|DROP)\s+/i', $sql);

                if ($isDDL || !$this->statement || $this->statement->columnCount() == 0 || $hasReturning) {
                    $this->connection->commit();
                }
            }

            return $result;
        } catch (\Exception $e) {
            // Firebird MVCC: Ignore "index already exists" errors for CREATE INDEX
            // This handles metadata visibility issues where indexes persist after table drop
            if (
                stripos($sql, 'CREATE') !== false && stripos($sql, 'INDEX') !== false &&
                stripos($e->getMessage(), 'already exists') !== false
            ) {
                // Commit and treat as success
                if ($this->transactionDepth == 0 && $this->connection && $this->connection->inTransaction()) {
                    $this->connection->commit();
                }
                return true;
            }

            // Firebird MVCC: Handle "cannot create index RDB$PRIMARY" during CREATE TABLE
            // After rapid DROP+CREATE cycles, metadata garbage collection may not have
            // completed, causing system index conflicts. Retry using RECREATE TABLE
            // which performs an atomic drop-and-create in a single metadata update.
            if (
                preg_match('/^\s*CREATE\s+TABLE\b/i', $sql)
                && stripos($e->getMessage(), 'cannot create index') !== false
                && stripos($e->getMessage(), 'RDB$PRIMARY') !== false
            ) {
                // Rollback the failed transaction
                if ($this->transactionDepth == 0 && $this->connection && $this->connection->inTransaction()) {
                    $this->connection->rollBack();
                }
                // Retry with RECREATE TABLE (atomic drop-if-exists + create)
                $retrySql = preg_replace('/^\s*CREATE\s+TABLE\b/i', 'RECREATE TABLE', $sql);
                $this->prepare($retrySql);
                $result = $this->statement->execute();
                if ($this->transactionDepth == 0 && $this->connection && $this->connection->inTransaction()) {
                    $this->connection->commit();
                }
                return $result;
            }

            // Ignore "table does not exist" errors for DROP TABLE
            // This handles the case where IF EXISTS was stripped in setQuery()
            if (
                stripos($sql, 'DROP') !== false && stripos($sql, 'TABLE') !== false &&
                strpos($e->getMessage(), '-607') !== false &&
                stripos($e->getMessage(), 'does not exist') !== false
            ) {
                // Commit and treat as success
                if ($this->transactionDepth == 0 && $this->connection && $this->connection->inTransaction()) {
                    $this->connection->commit();
                }
                return true;
            }

            // Rollback implicit transaction on error
            if ($this->transactionDepth == 0 && $this->connection && $this->connection->inTransaction()) {
                $this->connection->rollBack();
            }
            throw $e;
        }
    }

    /**
     * Frees up the memory used for the result set
     *
     * Closes the cursor and commits implicit transactions for SELECT queries.
     * This emulates autocommit behavior matching other drivers.
     *
     * @return  $this
     */
    protected function freeResult()
    {
        if (isset($this->statement) && method_exists($this->statement, 'closeCursor')) {
            $this->statement->closeCursor();
        }

        parent::freeResult();

        // Emulate autocommit: commit implicit transaction after fetching SELECT results
        // This matches other drivers' behavior where SELECT queries auto-commit
        if ($this->transactionDepth == 0 && $this->connection && $this->connection->inTransaction()) {
            $this->connection->commit();
        }

        return $this;
    }

    /**
     * Gets the auto-generated ID from the last INSERT
     *
     * Uses the ID captured from INSERT ... RETURNING if available.
     * Falls back to querying the generator if RETURNING wasn't used.
     *
     * @return  int|null
     */
    public function insertid()
    {
        // Prefer the ID from RETURNING clause (works with explicit IDs too)
        if ($this->lastInsertId !== null) {
            return $this->lastInsertId;
        }

        // Fallback: query the generator (only works for auto-generated IDs)
        if ($this->lastInsertTable === null) {
            return null;
        }

        // First try IDENTITY column generator (Firebird 3.0+)
        $generator = $this->findIdentityGenerator($this->lastInsertTable);

        // Fall back to legacy generator naming patterns
        if (!$generator) {
            $generator = $this->findTableGenerator($this->lastInsertTable);
        }

        if (!$generator) {
            return null;
        }

        return $this->getGeneratorValue($generator);
    }

    /**
     * Retrieves field information about the given table
     *
     * @param   string   $table     The name of the database table
     * @param   boolean  $typeOnly  True to only return field types
     * @return  array    An array of fields for the database table
     */
    public function getTableColumns($table, $typeOnly = true)
    {
        $this->commitBeforeMetadataQuery();

        $columns = [];
        $table = strtoupper($this->replacePrefix($table));

        $this->setQuery("
            SELECT
                TRIM(rf.RDB\$FIELD_NAME) AS field_name,
                f.RDB\$FIELD_TYPE AS field_type,
                f.RDB\$FIELD_SUB_TYPE AS field_sub_type,
                f.RDB\$FIELD_LENGTH AS field_length,
                f.RDB\$FIELD_PRECISION AS field_precision,
                f.RDB\$FIELD_SCALE AS field_scale,
                rf.RDB\$NULL_FLAG AS not_null,
                rf.RDB\$DEFAULT_SOURCE AS default_value
            FROM RDB\$RELATION_FIELDS rf
            JOIN RDB\$FIELDS f ON rf.RDB\$FIELD_SOURCE = f.RDB\$FIELD_NAME
            WHERE rf.RDB\$RELATION_NAME = " . $this->quote($table) . "
            ORDER BY rf.RDB\$FIELD_POSITION
        ");

        $fields = $this->loadObjectList();

        // Note: Normalize column names to lowercase for consistency across databases
        if ($typeOnly) {
            foreach ($fields as $field) {
                $name = strtolower(trim($field->field_name ?? ''));
                $columns[$name] = $this->convertFieldType(
                    $field->field_type,
                    $field->field_sub_type,
                    $field->field_length,
                    $field->field_scale
                );
            }
        } else {
            foreach ($fields as $field) {
                $name = strtolower(trim($field->field_name ?? ''));
                $type = $this->convertFieldType(
                    $field->field_type,
                    $field->field_sub_type,
                    $field->field_length,
                    $field->field_scale
                );

                // Normalize output to match MySQL format (with lowercase field names)
                $columns[$name] = (object) [
                    'Field'   => $name,  // Already lowercase from line above
                    'Type'    => $type,
                    'Null'    => empty($field->not_null) ? 'YES' : 'NO',
                    'Default' => $this->normalizeDefault($field->default_value),
                    'Key'     => '',  // Need separate query for primary key
                    'Extra'   => ''
                ];
            }
        }

        return $columns;
    }

    /**
     * Convert Firebird field type codes to readable type names
     *
     * @param   int       $type      The Firebird field type code
     * @param   int|null  $subType   The field sub-type
     * @param   int|null  $length    The field length
     * @param   int|null  $scale     The field scale
     * @return  string
     */
    protected function convertFieldType($type, $subType = null, $length = null, $scale = null)
    {
        // Firebird type codes
        $types = [
            7   => 'SMALLINT',
            8   => 'INTEGER',
            10  => 'FLOAT',
            12  => 'DATE',
            13  => 'TIME',
            14  => 'CHAR',
            16  => 'BIGINT',
            23  => 'BOOLEAN',
            27  => 'DOUBLE PRECISION',
            35  => 'TIMESTAMP',
            37  => 'VARCHAR',
            261 => 'BLOB',
        ];

        $typeName = $types[$type] ?? 'UNKNOWN';

        // Handle BLOB sub-types
        if ($type == 261) {
            if ($subType == 1) {
                return 'TEXT';
            }
            return 'BLOB';
        }

        // Handle numeric types with scale (DECIMAL/NUMERIC)
        if (in_array($type, [7, 8, 16]) && $scale !== null && $scale < 0) {
            return 'DECIMAL';
        }

        return $typeName;
    }

    /**
     * Normalize default value from Firebird format
     *
     * @param   mixed  $value  The raw default value
     * @return  mixed
     */
    protected function normalizeDefault($value)
    {
        if ($value === null) {
            return null;
        }

        $value = trim($value);

        // Remove "DEFAULT " prefix
        if (stripos($value, 'DEFAULT ') === 0) {
            $value = substr($value, 8);
        }

        // Check for NULL literal
        if (strtoupper(trim($value)) === 'NULL') {
            return null;
        }

        // Remove surrounding quotes
        if (preg_match("/^'(.*)'$/s", $value, $matches)) {
            return str_replace("''", "'", $matches[1]);
        }

        return trim($value);
    }

    /**
     * Retrieves key information about the given table
     *
     * @param   string  $table  A table name
     * @return  array
     */
    public function getTableKeys($table)
    {
        $this->commitBeforeMetadataQuery();

        $keys = [];
        $table = strtoupper($this->replacePrefix($table));

        // Get primary key
        $this->setQuery("
            SELECT TRIM(i.RDB\$FIELD_NAME) AS column_name
            FROM RDB\$RELATION_CONSTRAINTS rc
            JOIN RDB\$INDEX_SEGMENTS i ON rc.RDB\$INDEX_NAME = i.RDB\$INDEX_NAME
            WHERE rc.RDB\$RELATION_NAME = " . $this->quote($table) . "
            AND rc.RDB\$CONSTRAINT_TYPE = 'PRIMARY KEY'
            ORDER BY i.RDB\$FIELD_POSITION
        ");

        $pkColumns = $this->loadObjectList();
        foreach ($pkColumns as $idx => $col) {
            $keys['PRIMARY'][] = (object) [
                'Key_name'     => 'PRIMARY',
                'Column_name'  => strtolower(trim($col->column_name)),
                'Non_unique'   => 0,
                'Seq_in_index' => $idx + 1
            ];
        }

        // Get other indexes (exclude system indexes and primary key)
        $this->setQuery("
            SELECT
                TRIM(i.RDB\$INDEX_NAME) AS index_name,
                TRIM(s.RDB\$FIELD_NAME) AS column_name,
                i.RDB\$UNIQUE_FLAG AS is_unique,
                s.RDB\$FIELD_POSITION AS field_position
            FROM RDB\$INDICES i
            JOIN RDB\$INDEX_SEGMENTS s ON i.RDB\$INDEX_NAME = s.RDB\$INDEX_NAME
            WHERE i.RDB\$RELATION_NAME = " . $this->quote($table) . "
            AND (i.RDB\$SYSTEM_FLAG = 0 OR i.RDB\$SYSTEM_FLAG IS NULL)
            AND i.RDB\$INDEX_NAME NOT IN (
                SELECT RDB\$INDEX_NAME FROM RDB\$RELATION_CONSTRAINTS
                WHERE RDB\$CONSTRAINT_TYPE = 'PRIMARY KEY'
            )
            ORDER BY i.RDB\$INDEX_NAME, s.RDB\$FIELD_POSITION
        ");

        $indexes = $this->loadObjectList();
        foreach ($indexes as $index) {
            $name = strtolower(trim($index->index_name));
            // Append to array (like PRIMARY key) instead of overwriting
            $keys[$name][] = (object) [
                'Key_name'     => $name,
                'Column_name'  => strtolower(trim($index->column_name)),
                'Non_unique'   => $index->is_unique ? 0 : 1,
                'Seq_in_index' => $index->field_position + 1
            ];
        }

        return $keys;
    }

    /**
     * Check if a table has a specific key/index
     *
     * Firebird stores identifiers in UPPERCASE, so we need case-insensitive matching
     *
     * @param   string  $table  The table name
     * @param   string  $key    The key/index name
     * @return  bool
     */
    public function tableHasKey($table, $key)
    {
        $keys = $this->getTableKeys($table);

        if (!is_array($keys)) {
            return false;
        }

        // getTableKeys() stores 'PRIMARY' as-is and other indexes as lowercase
        return isset($keys[$key]) || isset($keys[strtolower($key)]);
    }

    /**
     * Gets an array of all tables in the database
     *
     * @return  array
     */
    public function getTableList()
    {
        $this->commitBeforeMetadataQuery();

        $this->setQuery("
            SELECT TRIM(RDB\$RELATION_NAME) AS table_name
            FROM RDB\$RELATIONS
            WHERE RDB\$SYSTEM_FLAG = 0
            AND RDB\$VIEW_BLR IS NULL
            ORDER BY RDB\$RELATION_NAME
        ");

        $tables = $this->loadColumn();
        // Normalize to lowercase for consistency with other databases
        return array_map('strtolower', $tables);
    }

    /**
     * Shows the table CREATE statement
     *
     * Note: Firebird doesn't have a direct equivalent to SHOW CREATE TABLE.
     * This reconstructs the CREATE statement from metadata.
     *
     * @param   string|array  $tables  A table name or list of table names
     * @return  array
     */
    public function getTableCreate($tables)
    {
        $result = [];

        foreach ((array) $tables as $table) {
            $tableName = strtoupper($this->replacePrefix($table));

            // Get columns
            $columns = $this->getTableColumns($table, false);
            $columnDefs = [];

            foreach ($columns as $name => $col) {
                $def = $this->quoteName($name) . ' ' . $col->Type;
                if ($col->Null === 'NO') {
                    $def .= ' NOT NULL';
                }
                if ($col->Default !== null) {
                    $def .= ' DEFAULT ' . $this->quote($col->Default);
                }
                $columnDefs[] = $def;
            }

            // Get primary key
            $pk = $this->getPrimaryKey($table);
            if ($pk) {
                $columnDefs[] = 'PRIMARY KEY (' . $this->quoteName($pk) . ')';
            }

            $result[$table] = 'CREATE TABLE ' . $this->quoteName($tableName) . " (\n    " .
                implode(",\n    ", $columnDefs) . "\n)";
        }

        return $result;
    }

    /**
     * Gets the database collation in use
     *
     * @return  string|bool
     */
    public function getCollation()
    {
        $this->commitBeforeMetadataQuery();

        $this->setQuery("
            SELECT TRIM(RDB\$CHARACTER_SET_NAME) AS charset
            FROM RDB\$DATABASE
        ");

        return $this->loadResult() ?: 'UTF8';
    }

    /**
     * Commit any pending transaction before querying metadata tables
     * to avoid MVCC deadlocks in Firebird
     *
     * @return void
     */
    private function commitBeforeMetadataQuery(): void
    {
        if ($this->transactionDepth == 0 && $this->connection && $this->connection->inTransaction()) {
            try {
                $this->connection->commit();
            } catch (\Exception $e) {
                // Ignore commit errors - transaction may already be committed.
                // Preserve context in debug logs for troubleshooting.
                $this->getLogger()->debug('Firebird metadata pre-commit ignored', [
                    'error' => $e->getMessage(),
                ]);
            }
        }
    }

    /**
     * Check if a table has an "ID" column (cached, pipeline-safe)
     *
     * Uses a direct PDO query to avoid recursion through setQuery()/execute().
     * Results are cached per table for the lifetime of the connection.
     *
     * @param   string  $table  Table name (unquoted)
     * @return  bool
     */
    protected function tableHasIdColumn(string $table): bool
    {
        $upperTable = strtoupper($this->replacePrefix($table));

        if (isset($this->tableIdColumnCache[$upperTable])) {
            return $this->tableIdColumnCache[$upperTable];
        }

        $result = false;
        try {
            $pdo = $this->getConnection()->getNativeConnection();
            $stmt = $pdo->prepare(
                "SELECT 1 FROM RDB\$RELATION_FIELDS " .
                "WHERE RDB\$RELATION_NAME = ? AND TRIM(RDB\$FIELD_NAME) = 'ID'"
            );
            $stmt->execute([$upperTable]);
            $result = (bool) $stmt->fetch();
            $stmt->closeCursor();
        } catch (\Exception $e) {
            $result = false;
        }

        $this->tableIdColumnCache[$upperTable] = $result;
        return $result;
    }

