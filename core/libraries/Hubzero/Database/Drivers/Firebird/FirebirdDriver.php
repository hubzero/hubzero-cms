    /**
     * Retrieves foreign key information for a table
     *
     * @param   string  $table  The table name
     * @return  array   Array of foreign key constraint objects
     */
    public function getForeignKeys($table)
    {
        $table = strtoupper($this->replacePrefix($table));

        $this->setQuery("
            SELECT
                TRIM(rc.RDB\$CONSTRAINT_NAME) AS constraint_name,
                TRIM(s.RDB\$FIELD_NAME) AS column_name,
                TRIM(ref_rc.RDB\$RELATION_NAME) AS referenced_table,
                TRIM(ref_s.RDB\$FIELD_NAME) AS referenced_column,
                TRIM(refc.RDB\$UPDATE_RULE) AS update_rule,
                TRIM(refc.RDB\$DELETE_RULE) AS delete_rule
            FROM RDB\$RELATION_CONSTRAINTS rc
            JOIN RDB\$INDEX_SEGMENTS s ON rc.RDB\$INDEX_NAME = s.RDB\$INDEX_NAME
            JOIN RDB\$REF_CONSTRAINTS refc ON rc.RDB\$CONSTRAINT_NAME = refc.RDB\$CONSTRAINT_NAME
            JOIN RDB\$RELATION_CONSTRAINTS ref_rc ON refc.RDB\$CONST_NAME_UQ = ref_rc.RDB\$CONSTRAINT_NAME
            JOIN RDB\$INDEX_SEGMENTS ref_s ON ref_rc.RDB\$INDEX_NAME = ref_s.RDB\$INDEX_NAME
                AND s.RDB\$FIELD_POSITION = ref_s.RDB\$FIELD_POSITION
            WHERE rc.RDB\$RELATION_NAME = " . $this->quote($table) . "
            AND rc.RDB\$CONSTRAINT_TYPE = 'FOREIGN KEY'
            ORDER BY rc.RDB\$CONSTRAINT_NAME, s.RDB\$FIELD_POSITION
        ");

        return $this->groupForeignKeyRows($this->loadObjectList(), [
            'group_key'       => fn($row) => strtoupper(trim($row->constraint_name ?? '')),
            'constraint_name' => fn($row) => strtolower(trim($row->constraint_name ?? '')),
            'column_name'     => fn($row) => strtolower(trim($row->column_name ?? '')),
            'foreign_table'   => fn($row) => strtolower(trim($row->referenced_table ?? '')),
            'foreign_column'  => fn($row) => strtolower(trim($row->referenced_column ?? '')),
            'on_update'       => fn($row) => trim($row->update_rule ?? ''),
            'on_delete'       => fn($row) => trim($row->delete_rule ?? ''),
        ]);
    }

