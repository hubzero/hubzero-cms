     * The current transaction depth (for savepoint support)
     *
     * @var int
     */
    protected $transactionDepth = 0;

    /**
     * Stored connection options for reconnection
     *
     * Firebird MVCC (Multi-Version Concurrency Control) can cause metadata
     * visibility issues where a transaction doesn't see recently committed
     * DDL changes. Reconnecting creates a fresh connection that sees all
     * committed changes.
     *
     * @var array
     */
    protected $connectionOptions = [];

    /**
     * The last table used in an INSERT statement
     *
     * Used as fallback for insertid() if RETURNING doesn't work.
     *
     * @var string|null
     */
    protected $lastInsertTable = null;

    /**
     * The ID returned from the last INSERT ... RETURNING statement
     *
     * @var int|null
     */
    protected $lastInsertId = null;

    /**
     * Cached row from RETURNING clause
     *
     * When execute() fetches a RETURNING row to extract the ID, we cache it
     * here so subsequent loadResult()/loadObject() calls can access it.
     *
     * @var array|null
     */
    protected $cachedReturningRow = null;

    /**
     * Cache of which tables have an "ID" column
     *
     * Used by setQuery() to decide whether to add RETURNING "ID" to INSERTs.
     * Bypasses the normal setQuery()/execute() pipeline to avoid recursion.
     *
     * @var array<string, bool>
     */
    protected $tableIdColumnCache = [];

    /**
     * @inheritdoc
     */
    protected function resetDriverState(array $options = []): void
    {
        $this->lastInsertTable = null;
        $this->lastInsertId = null;
        $this->cachedReturningRow = null;
        $this->tableIdColumnCache = [];
    }

    /**
     * Character used to quote identifiers
     *
     * @var string
     */
    protected $nameQuote = '"';

    /**
     * Constructs a new database object based on the given params
     *
     * @param   array  $options  The database connection params
     * @return  void
     * @throws  ConnectionFailedException  If the DSN is invalid or connection fails
     */
    public function __construct($options)
    {
        // Check for the Firebird PDO extension
        if (!in_array('firebird', \PDO::getAvailableDrivers())) {
            throw new ConnectionFailedException(
                'The PDO Firebird extension (pdo_firebird) is not installed or enabled.',
                500
            );
        }

        // Add "extra" options as needed
        if (!isset($options['extras'])) {
            $options['extras'] = [];
        }

        // Firebird requires ATTR_AUTOCOMMIT off for proper transaction support.
        // With autocommit on, rollback doesn't work correctly.
        $options['extras'][\PDO::ATTR_AUTOCOMMIT] = false;

        // =====================================================================
        // CRITICAL: Force column names to lowercase for consistency
        // =====================================================================
        // PDO_FIREBIRD returns column names in unpredictable case (usually lowercase)
        // while Firebird stores identifiers as uppercase. This creates constant
        // case-sensitivity bugs where code expects uppercase but gets lowercase.
        //
        // Setting ATTR_CASE = CASE_LOWER forces ALL column names to lowercase,
        // giving us consistent behavior. This means ALL code must use lowercase
        // when accessing result properties:
        //   $row->column_name  ✓ Correct
        //   $row->COLUMN_NAME  ✗ Wrong - will return null
        //
        // This affects:
        // - All fetch operations (fetchObject, fetchArray, fetchAssoc)
        // - System table queries (RDB$RELATIONS, RDB$RELATION_FIELDS, etc.)
        // - All test assertions
        // - getTableColumns(), getIndexes(), getForeignKeys(), etc.
        $options['extras'][\PDO::ATTR_CASE] = \PDO::CASE_LOWER;

        // Build DSN if not provided
        if (!isset($options['dsn'])) {
            $dsn = 'firebird:';

            // Database path (required)
            if (!empty($options['database'])) {
                // Format: hostname:path/to/database.fdb or just path for embedded
                if (!empty($options['host'])) {
                    // Use server mode - include host (even for localhost)
                    $host = $options['host'];
                    if (!empty($options['port']) && $options['port'] != 3050) {
                        $host .= '/' . $options['port'];
                    }
                    $dsn .= 'dbname=' . $host . ':' . $options['database'];
                } else {
                    // Embedded mode - no host specified
                    $dsn .= 'dbname=' . $options['database'];
                }
            }

            // Character set (default to UTF8)
            $charset = !empty($options['charset']) ? $options['charset'] : 'UTF8';
            $dsn .= ';charset=' . $charset;

            // Role (optional)
            if (!empty($options['role'])) {
                $dsn .= ';role=' . $options['role'];
            }

            $options['dsn'] = $dsn;
        }

        // Verify DSN format
        if (substr($options['dsn'], 0, 9) !== 'firebird:') {
            throw new ConnectionFailedException('Firebird DSN for PDO connection does not appear to be valid.', 500);
        }

        // Store connection options for potential reconnection
        // (needed for Firebird MVCC metadata visibility workarounds)
        $this->connectionOptions = $options;

        // Call parent construct
        parent::__construct($options);

        // Explicitly set ATTR_CASE on the connection to ensure it takes effect
        // This forces all column names in result sets to lowercase for consistency
        if ($this->connection instanceof \Hubzero\Database\ConnectionInterface) {
            $this->connection->setAttribute(\PDO::ATTR_CASE, \PDO::CASE_LOWER);
        }
    }

    /**
     * Get a property from a result object, handling case sensitivity
     *
     * This helper provides fallback support in case PDO::ATTR_CASE doesn't work
     * as expected. It tries both uppercase and lowercase property names.
     *
     * @param   object  $obj   The result object
     * @param   string  $name  The property name (should be uppercase)
     * @return  mixed   The property value, or null if not found
     */
    protected function getResultProperty($obj, string $name)
    {
        return $obj->$name ?? $obj->{strtolower($name)} ?? null;
    }

    /**
     * Reconnects to the database to ensure fresh metadata visibility
     *
     * FIREBIRD MVCC WORKAROUND:
     * Firebird's MVCC architecture means transactions see a snapshot of the
     * database from when they started. Even after DDL changes are committed,
     * the current connection may not see updated metadata in system tables.
     *
     * Symptoms of this issue:
     * - getTableColumns() returns empty array after CREATE TABLE
     * - tableExists() returns false for newly created tables
     * - JOIN queries to RDB$FIELDS return no rows (MVCC visibility gap)
     * - Renamed tables appear to not exist
     *
     * Solution: Reconnecting creates a new connection with a fresh transaction
     * that sees all committed changes. This is the most reliable workaround.
     *
     * Usage pattern:
     *   $db->exec("CREATE TABLE foo (id INTEGER)");
     *   $db->reconnect();  // Essential!
     *   $columns = $db->getTableColumns('foo');  // Now works
     *
     * Alternative: Query RDB$RELATION_FIELDS and RDB$FIELDS separately instead
     * of using JOINs (see getTableColumns() implementation).
     *
     * IMPORTANT: Only call this when NOT in an active transaction, as it will
     * lose any uncommitted changes.
     *
     * @throws  \RuntimeException  If called during an active transaction
     * @return  void
     */
    protected function reconnect()
    {
        if ($this->transactionDepth > 0) {
            throw new \RuntimeException(
                'Cannot reconnect during an active transaction (would lose uncommitted changes)'
            );
        }

        // Commit any implicit transaction before closing
        $connection = $this->connection;
        $native = $connection->getNativeConnection();
        if ($native && $native->inTransaction()) {
            $native->commit();
        }

        // Disconnect (drops internal PDO but keeps PdoConnection config for reconnect)
        $connection->disconnect();

        // PDO_FIREBIRD limitation: Even after reconnecting, Firebird server-side metadata
        // cache may not have flushed. Add a small delay to ensure metadata is visible.
        // This is a workaround for a known PDO_FIREBIRD + Firebird MVCC limitation.
        usleep(50000); // 50ms delay

        // Reconnect — PdoConnection stores DSN/credentials, so connect() creates fresh PDO
        $connection->connect();
    }

    /**
     * Sets the SQL statement string for later execution
     *
     * Firebird requires FROM clause for simple SELECT statements.
     * This override adds FROM RDB$DATABASE when needed.
     *
     * @param   string  $query     The SQL statement to set
     * @param   array   $bindings  Optional bindings to bind to the query
     * @return  $this
     */
    public function setQuery($query)
    {
        // Enforce raw query mode at this level — ensures the
        // backtrace correctly identifies external callers.
        // The flag prevents parent::setQuery() from re-checking.
        $shouldEnforce = $this->rawQueryMode !== 'permissive'
            && !$this->rawQueryModeEnforced;

        if ($shouldEnforce) {
            $this->rawQueryModeEnforced = true;
        }

        try {
            if ($shouldEnforce) {
                $this->enforceRawQueryMode((string) $query);
            }

            $query = (string) $query;

            // Firebird requires FROM clause - fix bare SELECT expressions
            // Examples: SELECT 1, SELECT CURRENT_TIMESTAMP, etc.
            // Only add FROM RDB$DATABASE if there's no FROM anywhere in the query
            if (preg_match('/^\s*SELECT\s/i', $query) && !preg_match('/\bFROM\b/i', $query)) {
                $query = rtrim($query, "; \t\n\r\0\x0B") . ' FROM RDB$DATABASE';
            }

            // Convert TEXT type to BLOB SUB_TYPE 1 (Firebird text storage type)
            // Match TEXT as a standalone word (not part of another word like FULLTEXT)
            $query = preg_replace('/\b(TEXT)\b(?!\s+SUB_TYPE)/i', 'BLOB SUB_TYPE 1', $query);

            // Remove size from INTEGER types - Firebird doesn't support INTEGER(n)
            $query = preg_replace('/\b(INTEGER|INT|SMALLINT|BIGINT)\s*\(\s*\d+\s*\)/i', '$1', $query);

            // Convert TINYINT to SMALLINT (Firebird doesn't have TINYINT)
            // TINYINT(1) is commonly used for booleans, convert to SMALLINT
            $query = preg_replace('/\bTINYINT\s*\(\s*\d+\s*\)/i', 'SMALLINT', $query);
            $query = preg_replace('/\bTINYINT\b/i', 'SMALLINT', $query);

            // Convert DATETIME to TIMESTAMP (Firebird doesn't have DATETIME)
            $query = preg_replace('/\bDATETIME\b/i', 'TIMESTAMP', $query);

            // Remove size from BOOLEAN - Firebird doesn't support BOOLEAN(n)
            $query = preg_replace('/\bBOOLEAN\s*\(\s*\d+\s*\)/i', 'BOOLEAN', $query);

            // Remove UNSIGNED - Firebird doesn't support UNSIGNED modifier
            $query = preg_replace('/\bUNSIGNED\b/i', '', $query);

            // Convert AUTOINCREMENT to GENERATED BY DEFAULT AS IDENTITY
            // IMPORTANT: In Firebird, GENERATED must come BEFORE PRIMARY KEY and needs NOT NULL
            // Pattern: INTEGER PRIMARY KEY AUTOINCREMENT
            //       -> INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY
            if (stripos($query, 'GENERATED') === false) {
                // First, handle the special case of INTEGER PRIMARY KEY AUTOINCREMENT
                $query = preg_replace(
                    '/\b(INTEGER|INT|BIGINT|SMALLINT)\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/i',
                    '$1 GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY',
                    $query
                );
                // Handle INTEGER PRIMARY KEY (without AUTOINCREMENT)
                $query = preg_replace(
                    '/\b(INTEGER|INT|BIGINT|SMALLINT)\s+PRIMARY\s+KEY\b/i',
                    '$1 GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY',
                    $query
                );
                // Then handle standalone AUTOINCREMENT (less common)
                $query = preg_replace('/\bAUTOINCREMENT\b/i', 'GENERATED BY DEFAULT AS IDENTITY NOT NULL', $query);
            } else {
                // If GENERATED is already present, just remove AUTOINCREMENT
                $query = preg_replace('/\s*\bAUTOINCREMENT\b/i', '', $query);
            }

            // Remove column positioning (AFTER/BEFORE column_name) - Firebird doesn't support it
            $query = preg_replace('/\s+(AFTER|BEFORE)\s+[`"\[]?\w+[`"\]]?/i', '', $query);

            // Remove IF EXISTS/IF NOT EXISTS - Firebird doesn't support these clauses
            // Strip from DROP TABLE, DROP INDEX, ALTER TABLE...DROP, etc.
            $query = preg_replace('/\b(DROP\s+(?:TABLE|INDEX|CONSTRAINT|COLUMN))\s+IF\s+EXISTS\s+/i', '$1 ', $query);
            $query = preg_replace('/\bIF\s+NOT\s+EXISTS\s+/i', '', $query);

            // Quote VALUE reserved word when used as column name
            // VALUE is a Firebird reserved word (SQL function)
            // Match: value as a column name (preceded by comma, space, or paren, not already quoted)
            // Don't match: VALUES keyword or already quoted identifiers
            $query = preg_replace_callback(
                '/(\(|,|\s)(?<!VALUES\s)(value)'
                . '(\s|,|\)|\s+(?:INTEGER|VARCHAR|SMALLINT|BIGINT|TEXT'
                . '|TIMESTAMP|DATE|BLOB|CHAR|DOUBLE|FLOAT))/i',
                function ($matches) {
                    return $matches[1] . '"VALUE"' . $matches[3];
                },
                $query
            );

            // Automatically add RETURNING "ID" for INSERT statements that target
            // tables with an ID column. This makes insertid() work transparently.
            if (
                preg_match('/^\s*INSERT\s+INTO\s+"?([^"\s(]+)"?/i', $query, $insertMatch)
                && !preg_match('/\bRETURNING\b/i', $query)
            ) {
                $tableName = $insertMatch[1];
                if ($this->tableHasIdColumn($tableName)) {
                    $query = rtrim($query, "; \t\n\r\0\x0B") . ' RETURNING "ID"';
                }
            }

            return parent::setQuery($query);
        } finally {
            if ($shouldEnforce) {
                $this->rawQueryModeEnforced = false;
            }
        }
    }

