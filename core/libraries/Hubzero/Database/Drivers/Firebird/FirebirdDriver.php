    /**
     * Returns the SQL for extracting a substring based on a delimiter
     *
     * Firebird doesn't have SUBSTRING_INDEX. This is an approximation.
     *
     * @param   string  $str    The string expression
     * @param   string  $delim  The delimiter to search for
     * @param   int     $count  The occurrence count
     * @return  string
     */
    public function sqlSubstringIndex(string $str, string $delim, int $count): string
    {
        $quotedDelim = $this->quote($delim);
        $delimLen = strlen($delim);

        if ($count == 1) {
            // Get everything before the first delimiter
            return "CASE WHEN POSITION(" . $quotedDelim . " IN " . $str . ") > 0 "
                 . "THEN SUBSTRING(" . $str . " FROM 1 FOR POSITION(" . $quotedDelim . " IN " . $str . ") - 1) "
                 . "ELSE " . $str . " END";
        } elseif ($count == -1) {
            // Get everything after the last delimiter
            return "CASE WHEN POSITION(" . $quotedDelim . " IN " . $str . ") > 0 "
                 . "THEN SUBSTRING(" . $str . " FROM POSITION("
                 . $quotedDelim . " IN " . $str . ") + " . $delimLen . ") "
                 . "ELSE " . $str . " END";
        }

        // For other counts, return the full string (limited support)
        return $str;
    }

