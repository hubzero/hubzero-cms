    /**
     * Get CHECK constraints for table
     *
     * @param   string  $table  Table name
     * @return  array
     */
    public function getCheckConstraints(string $table): array
    {
        $table = strtoupper($this->replacePrefix($table));

        $sql = "SELECT 
                   rc.RDB\$CONSTRAINT_NAME as constraint_name, 
                   t.RDB\$TRIGGER_SOURCE as check_clause
                FROM RDB\$RELATION_CONSTRAINTS rc
                JOIN RDB\$CHECK_CONSTRAINTS cc ON rc.RDB\$CONSTRAINT_NAME = cc.RDB\$CONSTRAINT_NAME
                JOIN RDB\$TRIGGERS t ON cc.RDB\$TRIGGER_NAME = t.RDB\$TRIGGER_NAME
                WHERE rc.RDB\$CONSTRAINT_TYPE = 'CHECK' 
                AND rc.RDB\$RELATION_NAME = " . $this->quote($table);

        $this->setQuery($sql);
        $results = $this->loadObjectList();

        $constraints = [];
        foreach ($results as $row) {
            $constraints[] = (object) [
                'name' => trim($row->constraint_name),
                'expression' => trim($row->check_clause)
            ];
        }

        return $constraints;
    }

    /**
     * Add stored (computed) column
     *
     * Firebird uses COMPUTED BY syntax.
     *
     * @param   string       $table       Table name
     * @param   string       $column      Column name
     * @param   string       $expression  SQL expression
     * @param   string|null  $type        Column type (ignored by Firebird)
     * @return  bool
     */
    public function addStoredColumn(string $table, string $column, string $expression, ?string $type = null): bool
    {
        $table = $this->replacePrefix($table);
        $this->setQuery("ALTER TABLE $table ADD $column COMPUTED BY ($expression)");
        return $this->execute();
    }

    /**
     * Add virtual (computed) column
     *
     * Firebird 'COMPUTED BY' columns are virtual (calculated at read time).
     *
     * @param   string       $table       Table name
     * @param   string       $column      Column name
     * @param   string       $expression  SQL expression
     * @param   string|null  $type        Column type (ignored by Firebird)
     * @return  bool
     */
    public function addVirtualColumn(string $table, string $column, string $expression, ?string $type = null): bool
    {
        // In Firebird, COMPUTED BY columns are virtual
        return $this->addStoredColumn($table, $column, $expression, $type);
    }

    /**
     * Get global configuration variables
     *
     * @return  array
     */
    public function getGlobalVariables(): array
    {
        // Firebird doesn't have a simple key-value store for global variables
        // We can return some context info
        $this->setQuery("SELECT 
            rdb\$get_context('SYSTEM', 'ENGINE_VERSION') as engine_version,
            rdb\$get_context('SYSTEM', 'NETWORK_PROTOCOL') as protocol,
            rdb\$get_context('SYSTEM', 'DB_NAME') as db_name
            FROM rdb\$database");

        try {
            return (array) $this->loadObject();
        } catch (\Exception $e) {
            return [];
        }
    }

