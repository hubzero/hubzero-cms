    /**
     * Quote an identifier name
     *
     * @param   string       $name  The identifier name
     * @param   string|null  $as    An optional alias
     * @return  string
     */
    public function quoteName($name, $as = null)
    {
        if (is_array($name)) {
            $quotedArray = [];
            foreach ($name as $k => $v) {
                $quotedArray[$k] = $this->quoteName($v);
            }
            return $quotedArray;
        }

        $parts = (strpos($name, '.') !== false) ? explode('.', $name) : (array)$name;
        $bits  = array();

        foreach ($parts as $part) {
            if ($part === '*') {
                $bits[] = $part;
            } else {
                // Trim existing quotes and uppercase (Firebird stores unquoted identifiers as uppercase)
                // PDO::ATTR_CASE=PDO::CASE_LOWER normalizes returned column names to lowercase for ORM
                $part = strtoupper(trim($part, '`"'));
                $bits[] = sprintf($this->wrapper, $part);
            }
        }

        $string = implode('.', $bits);

        if (isset($as)) {
            $as = strtoupper(trim($as, '`"'));
            $string .= ' AS ' . sprintf($this->wrapper, $as);
        }

        return $string;
    }

    /**
     * Quotes table names and columns, handling "table AS alias" format
     *
     * Overrides parent to uppercase identifiers for Firebird.
     *
     * @param   string  $value  The table definition
     * @return  string
     */
    public function wrap($value)
    {
        $value = trim((string) $value);

        if ($value === '') {
            return '';
        }

        // Preserve derived-table expressions like "(SELECT ...)" as raw SQL.
        if ($value[0] === '(' && substr($value, -1) === ')') {
            return $value;
        }

        // Handle explicit aliases, including derived tables:
        // "(SELECT ... AS x ...) AS alias"
        if (preg_match('/^(.+)\s+as\s+([^\s]+)$/is', $value, $matches)) {
            return $this->wrap($matches[1]) . ' AS ' . $this->wrap($matches[2]);
        }

        // Handle shorthand alias format: "table alias" (without AS keyword)
        if (preg_match('/^(.+)\s+([^\s]+)$/s', $value, $matches)) {
            return $this->wrap($matches[1]) . ' AS ' . $this->wrap($matches[2]);
        }

        $quoted = [];
        $parts  = explode('.', $value);

        foreach ($parts as $part) {
            $part = trim($part);
            if ($part === '*') {
                $quoted[] = $part;
            } else {
                // Uppercase before quoting (Firebird stores unquoted identifiers as uppercase)
                $part = strtoupper(trim($part, '`"'));
                $quoted[] = sprintf($this->wrapper, $part);
            }
        }

        return implode('.', $quoted);
    }

