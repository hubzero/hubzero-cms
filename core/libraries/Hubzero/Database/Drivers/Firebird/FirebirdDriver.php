    /**
     * Gets index information for a table
     *
     * @param   string  $table  The table name
     * @return  array
     */
    public function getIndexes($table)
    {
        $table = strtoupper($this->replacePrefix($table));
        $indexes = [];

        // Note: "position" is a reserved word in Firebird, so we use "field_pos" as alias
        // Firebird PDO returns uppercase column names, so we access properties in uppercase
        $this->setQuery("
            SELECT
                TRIM(i.RDB\$INDEX_NAME) AS INDEX_NAME,
                i.RDB\$UNIQUE_FLAG AS IS_UNIQUE,
                TRIM(seg.RDB\$FIELD_NAME) AS COLUMN_NAME,
                seg.RDB\$FIELD_POSITION AS FIELD_POS
            FROM RDB\$INDICES i
            JOIN RDB\$INDEX_SEGMENTS seg ON i.RDB\$INDEX_NAME = seg.RDB\$INDEX_NAME
            WHERE i.RDB\$RELATION_NAME = " . $this->quote($table) . "
            AND (i.RDB\$SYSTEM_FLAG = 0 OR i.RDB\$SYSTEM_FLAG IS NULL)
            ORDER BY i.RDB\$INDEX_NAME, seg.RDB\$FIELD_POSITION
        ");

        $rows = $this->loadObjectList();

        foreach ($rows as $row) {
            // PDO returns lowercase property names with ATTR_CASE = CASE_LOWER
            $name = trim($row->index_name ?? '');
            // Uppercase the name for consistency with Firebird's uppercase identifier storage
            $nameUpper = strtoupper($name);

            if (!isset($indexes[$nameUpper])) {
                $indexes[$nameUpper] = (object) [
                    'name'    => $nameUpper,
                    'columns' => [],
                    'unique'  => (bool) $row->is_unique,
                ];
            }

            $indexes[$nameUpper]->columns[] = strtoupper(trim($row->column_name ?? ''));
        }

        return $indexes;
    }

