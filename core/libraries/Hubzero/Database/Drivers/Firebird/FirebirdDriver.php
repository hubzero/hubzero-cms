    /**
     * Drops a table
     *
     * @param   string   $tableName  The table name
     * @param   boolean  $ifExists   Use IF EXISTS (not supported in older Firebird)
     * @return  $this
     */
    public function dropTable($tableName, $ifExists = true)
    {
        $tableName = strtoupper($this->replacePrefix($tableName));

        if ($ifExists && !$this->tableExists($tableName)) {
            return $this;
        }

        // Firebird: Get primary key BEFORE dropping table (needed for generator cleanup)
        $pkColumn = $this->getPrimaryKey($tableName);

        // Firebird: Drop all user-created indexes first to prevent metadata visibility issues
        $this->setQuery("
            SELECT TRIM(RDB\$INDEX_NAME)
            FROM RDB\$INDICES
            WHERE RDB\$RELATION_NAME = " . $this->quote($tableName) . "
            AND RDB\$SYSTEM_FLAG = 0
            AND RDB\$INDEX_NAME NOT STARTING WITH 'RDB\$'
        ");
        $indexes = $this->loadColumn();

        foreach ($indexes as $indexName) {
            try {
                $this->setQuery('DROP INDEX ' . $this->quoteName(trim($indexName)));
                $this->execute();
            } catch (\Exception $e) {
                // Ignore errors dropping indexes
            }
        }

        // Firebird: Drop all triggers for this table
        $this->setQuery("
            SELECT TRIM(RDB\$TRIGGER_NAME)
            FROM RDB\$TRIGGERS
            WHERE RDB\$RELATION_NAME = " . $this->quote($tableName) . "
            AND RDB\$SYSTEM_FLAG = 0
        ");
        $triggers = $this->loadColumn();

        foreach ($triggers as $triggerName) {
            try {
                $this->setQuery('DROP TRIGGER ' . $this->quoteName(trim($triggerName)));
                $this->execute();
            } catch (\Exception $e) {
                // Ignore errors dropping triggers
            }
        }

        $this->setQuery($this->getSchemaGrammar()->compileDrop($tableName, false));
        $this->execute();

        // Firebird: Drop associated generator(s)
        // Try to find and drop generator using standard naming pattern
        if ($pkColumn) {
            $generatorName = 'GEN_' . $tableName . '_' . strtoupper($pkColumn);
            try {
                $this->dropSequence($generatorName, true);
            } catch (\Exception $e) {
                // Ignore errors dropping generator
            }
        }

        // Firebird: Commit to ensure metadata changes are visible immediately
        // This prevents "index already exists" errors when recreating tables in tests
        if ($this->connection && $this->connection->inTransaction() && $this->transactionDepth == 0) {
            $this->connection->commit();
        }

        return $this;
    }

    /**
     * Starts a transaction
     *
     * @return  void
     */
    public function transactionStart()
    {
        if ($this->transactionDepth == 0) {
            // If there's already an implicit transaction from previous operations,
            // commit it first to ensure those changes are persisted before we start
            // a new explicit transaction. This prevents previous work from being
            // accidentally rolled back with the new transaction.
            if ($this->connection && $this->connection->inTransaction()) {
                $this->connection->commit();
            }
            if ($this->connection) {
                $this->connection->beginTransaction();
            }
        } else {
            $this->setQuery('SAVEPOINT SP_' . $this->transactionDepth)->execute();
        }

        $this->transactionDepth++;
    }

    /**
     * Commits a transaction
     *
     * @return  void
     */
    public function transactionCommit()
    {
        if ($this->transactionDepth <= 0) {
            return;
        }

        $this->transactionDepth--;

        if ($this->transactionDepth == 0) {
            if ($this->connection) {
                $this->connection->commit();
            }
        } else {
            $this->setQuery('RELEASE SAVEPOINT SP_' . $this->transactionDepth)->execute();
        }
    }

    /**
     * Rolls back a transaction
     *
     * @return  void
     */
    public function transactionRollback()
    {
        if ($this->transactionDepth <= 0) {
            return;
        }

        $this->transactionDepth--;

        if ($this->transactionDepth == 0) {
            if ($this->connection) {
                $this->connection->rollBack();
            }
        } else {
            $this->setQuery('ROLLBACK TO SAVEPOINT SP_' . $this->transactionDepth)->execute();
