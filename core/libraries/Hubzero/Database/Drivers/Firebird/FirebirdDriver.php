        'text'       => 'BLOB SUB_TYPE 1',
        'mediumText' => 'BLOB SUB_TYPE 1',
        'longText'   => 'BLOB SUB_TYPE 1',

        // Numeric types
        'float'   => 'FLOAT',
        'double'  => 'DOUBLE PRECISION',
